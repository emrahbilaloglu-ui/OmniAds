# The complete fingerprint of one database, as key=value lines.
fingerprint_of() {
  local database="$1" counts
  counts="$(table_counts_on "${database}")"
  printf 'identity=%s\n' "$(db_sql_on "${database}" "SELECT current_database() || '|' || system_identifier::text FROM pg_control_system();" | tr -d '[:space:]')"
  printf 'schema_identity=%s\n' "$(schema_identity_on "${database}")"
  printf 'selected_binding_hash=%s\n' "$(selected_binding_hash_on "${database}")"
  if counts_have_table "${counts}" provider_connections; then
    printf 'connection_generation_hash=%s\n' "$(connection_generation_hash_on "${database}")"
  else
    printf 'connection_generation_hash=absent\n'
  fi
  if counts_have_table "${counts}" integration_credentials; then
    printf 'credential_generation_hash=%s\n' "$(credential_generation_hash_on "${database}")"
  else
    printf 'credential_generation_hash=absent\n'
  fi
  if counts_have_table "${counts}" provider_account_assignments; then
    printf 'assignment_hash=%s\n' "$(assignment_hash_on "${database}")"
  else
    printf 'assignment_hash=absent\n'
  fi
  if counts_have_table "${counts}" sync_release_gates; then
    printf 'release_gate_hash=%s\n' "$(release_gate_hash_on "${database}")"
  else
    printf 'release_gate_hash=absent\n'
  fi
  printf '%s\n' "${counts}" | sed '/^$/d' | sed 's/^/count./'
}

# ── F21.2: a FRESH backup, scratch-restored, bound to this database ────────
#
# Preflight used to grep somebody else's manifest for `scratch_restore_verified=yes`.
# That manifest could have been written months ago, against another database, by
# a job whose artifact has since been rotated away — and the core backup it
# describes deliberately omits provider_connections, integration_credentials and
# the account assignments, which are precisely the rows a bad Sync migration
# destroys. A rollback plan that omits the data at risk is not a rollback plan.

backup_dir_for_epoch() { printf '%s/%s' "${BACKUP_ROOT}" "$1"; }

db_free_bytes_for() {
  db_run "df -Pk $(printf %q "$1") | awk 'NR==2 {print \$4 * 1024}'" | tr -d '[:space:]'
}

db_logical_bytes() {
  db_sql "SELECT pg_database_size(current_database())::text;" | tr -d '[:space:]'
}

# The tables whose DATA the rollback artifact deliberately does not carry, read
# from the SAME policy file the daily backup uses. One source of truth: a table
# cannot be tier B for the backup and tier A for the cutover.
RECOVERY_POLICY_FILE="${SYNC_CUTOVER_RECOVERY_POLICY:-${CUTOVER_DIR}/recovery-policy.tsv}"

# The policy decides which tables the rollback artifact carries, so a MISSING or
# ALTERED policy silently changes what "a complete rollback" means. If the
# delivered manifest pins its digest, it must match; and if the policy is absent
# entirely the wrapper refuses rather than quietly treating every table as tier A
# and then failing the capacity gate for a reason that looks unrelated.
assert_recovery_policy() {
  local pinned actual
  [ -f "${RECOVERY_POLICY_FILE}" ] \
    || die "no recovery policy at ${RECOVERY_POLICY_FILE}; it is delivered with the wrapper, so this wrapper was not installed by a deploy of this release"
  pinned="$(awk -F= '$1 == "delivered_policy_sha256" { print $2 }' "${WRAPPER_MANIFEST}" 2>/dev/null | tr -d '[:space:]')"
  if [ -n "${pinned}" ]; then
    actual="$(sha256_file "${RECOVERY_POLICY_FILE}")"
    [ "${pinned}" = "${actual}" ] \
      || die "the recovery policy hashes ${actual}, the delivered manifest pins ${pinned}. It was edited on this host; re-deliver it, do NOT edit it in place."
  fi
}

tier_b_table_list() {
  [ -f "${RECOVERY_POLICY_FILE}" ] || return 0
  awk -F'\t' '/^[[:space:]]*#/ { next } NF >= 2 && $2 == "B" { print $1 }' \
    "${RECOVERY_POLICY_FILE}" | LC_ALL=C sort -u
}

# A SQL list literal of the tier-B tables, or an impossible name when there are
# none, so the predicates below stay valid either way.
tier_b_sql_list() {
  local list first=1 out=""
  list="$(tier_b_table_list)"
  if [ -z "${list}" ]; then printf "''" ; return 0; fi
  while IFS= read -r t; do
    [ -n "${t}" ] || continue
    if [ "${first}" = "1" ]; then out="'${t}'"; first=0; else out="${out},'${t}'"; fi
  done <<EOF
${list}
EOF
  printf '%s' "${out}"
}

# What the ARTIFACT actually has to hold: heap + TOAST of the tables whose data
# it carries. Indexes are excluded because pg_dump ships CREATE INDEX, not index
# pages — on this database that is 47 of 136 GiB, and counting it was what made
# the old gate demand a filesystem nobody has.
db_included_dump_input_bytes() {
  db_sql "SELECT COALESCE(sum(pg_relation_size(c.oid) + COALESCE(pg_total_relation_size(c.reltoastrelid),0)),0)::text
          FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
          WHERE n.nspname='public' AND c.relkind='r'
            AND c.relname NOT IN ($(tier_b_sql_list));" | tr -d '[:space:]'
}

# What a SCRATCH RESTORE of that artifact inflates to: the same tables with their
# indexes rebuilt. This lands in the PostgreSQL data directory, not in
# BACKUP_ROOT, so it is measured against a different filesystem.
db_included_restored_bytes() {
  db_sql "SELECT COALESCE(sum(pg_total_relation_size(c.oid)),0)::text
          FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
          WHERE n.nspname='public' AND c.relkind='r'
            AND c.relname NOT IN ($(tier_b_sql_list));" | tr -d '[:space:]'
}

db_data_directory() {
  db_sql "SHOW data_directory;" | tr -d '[:space:]'
}

assert_capacity_for_migration() {
  local free logical required data_dir
  data_dir="$(db_data_directory)"
  [ -n "${data_dir}" ] || die "could not read the PostgreSQL data directory on the database host; refusing to migrate blind"
  free="$(db_free_bytes_for "${data_dir}" || true)"
  logical="$(db_logical_bytes || true)"
  case "${free}" in
    "" | *[!0-9]*) die "could not read free space on the database host's PostgreSQL data directory; refusing to migrate blind" ;;
  esac
  case "${logical}" in
    "" | *[!0-9]*) die "could not read the logical size of ${DB_NAME}; refusing to migrate blind" ;;
  esac
  # The backfill rewrites matched rows and the concurrent index builds need room
  # for the new relations plus WAL. Half the database again, with a 5 GiB floor,
  # is the smallest defensible headroom.
  required=$(( logical / 2 ))
  if [ "${required}" -lt 5368709120 ]; then required=5368709120; fi
  log "db free=${free}B logical=${logical}B required=${required}B"
  [ "${free}" -ge "${required}" ] \
    || die "insufficient free space on the database host: ${free}B free, ${required}B required for a ${logical}B database"
}

take_verified_backup() {
  local epoch="$1" dir artifact manifest scratch free logical prior_input prior_bytes sizing_basis artifact_bytes dump_input restored data_dir scratch_free artifact_required scratch_required exclude_flags
  dir="$(backup_dir_for_epoch "${epoch}")"
  artifact="${dir}/full.dump"
  manifest="${dir}/cutover-backup.manifest"
  scratch="adsecute_cutover_scratch_${epoch}"
  # PostgreSQL identifiers are limited to 63 bytes and the epoch carries a sha
  # prefix and a timestamp, so the scratch name is truncated deliberately rather
  # than silently by the server.
  scratch="$(printf '%s' "${scratch}" | tr -c 'a-z0-9_' '_' | cut -c1-60)"

  mkdir -p "${dir}" && chmod 0700 "${dir}" \
    || die "could not create ${dir} on this host"

  # Measured against what this artifact actually contains and where each part
  # lands — not against pg_database_size.
  #
  # The old gate demanded `logical + logical/4` under BACKUP_ROOT: on this
  # database 170 GiB, on a filesystem with 30. It was wrong twice over. It
  # counted 47 GiB of INDEX pages that pg_dump never writes, and it charged the
  # scratch restore to BACKUP_ROOT when a restore inflates into the PostgreSQL
  # DATA directory, which is usually a different filesystem entirely.
  #
  # The rollback artifact carries tier-A data only. That is sound because the
  # migration's write-set was proven: it adds columns and indexes to the tier-B
  # tables and mutates no pre-existing column of any of them, so undoing the
  # migration never needs their rows. Their DATA is archived separately by the
  # daily backup; their SCHEMA is in this artifact.
  logical="$(db_logical_bytes)"
  dump_input="$(db_included_dump_input_bytes)"
  restored="$(db_included_restored_bytes)"
  data_dir="$(db_data_directory)"
  # The artifact filesystem is local to THIS host now, so it is measured here
  # rather than over ssh on the database host.
  free="$(df -Pk "${BACKUP_ROOT}" 2>/dev/null | awk 'NR==2 {print $4 * 1024}' | tr -d '[:space:]')"
  scratch_free="$(db_free_bytes_for "${data_dir}")"
  case "${free}" in "" | *[!0-9]*) die "could not read free space for ${BACKUP_ROOT} on the database host" ;; esac
  case "${dump_input}" in "" | *[!0-9]*) die "could not measure the artifact's included dataset; refusing to back up blind" ;; esac
  case "${restored}" in "" | *[!0-9]*) die "could not measure the scratch-restore target size; refusing to back up blind" ;; esac
  case "${scratch_free}" in "" | *[!0-9]*) die "could not read free space for the data directory ${data_dir}" ;; esac

  # Sizing the artifact.
  #
  # The uncompressed input is an upper bound, but on this data it is a wildly
  # pessimistic one: measured on production, a 30.2 GiB tier-A input compresses
  # to a 1.40 GiB artifact — roughly 21x, because tier-A rows are small and
  # highly repetitive. Gating on the uncompressed figure would refuse a cutover
  # that fits twenty times over, which is how a safety check turns into a
  # phantom blocker.
  #
  # So: prefer EVIDENCE. If a previous artifact recorded both its input and its
  # resulting size, use that ratio with a 3x safety margin. With no evidence,
  # fall back to a deliberately cautious eighth of the input — still far above
  # any ratio observed here — and never below a 2 GiB floor.
  #
  # This is defence in depth, not the only protection: if the dump runs out of
  # space anyway, pg_dump fails and the phase dies before anything migrates.
  prior_input=""; prior_bytes=""
  if [ -f "${BACKUP_ROOT}/last-artifact-sizing" ]; then
    prior_input="$(awk -F= '$1=="input_bytes"{print $2}' "${BACKUP_ROOT}/last-artifact-sizing" | tr -d '[:space:]')"
    prior_bytes="$(awk -F= '$1=="artifact_bytes"{print $2}' "${BACKUP_ROOT}/last-artifact-sizing" | tr -d '[:space:]')"
  fi
  case "${prior_input}${prior_bytes}" in
    "" | *[!0-9]*) artifact_required=$(( dump_input / 8 )) ; sizing_basis="no_prior_measurement" ;;
    *)
      if [ "${prior_input}" -gt 0 ] 2>/dev/null; then
        artifact_required=$(( dump_input * prior_bytes * 3 / prior_input ))
        sizing_basis="measured_ratio_${prior_bytes}_over_${prior_input}"
      else
        artifact_required=$(( dump_input / 8 )); sizing_basis="no_prior_measurement"
      fi ;;
  esac
  if [ "${artifact_required}" -lt 2147483648 ]; then artifact_required=2147483648; fi
  log "capacity: artifact sizing basis=${sizing_basis}"
  scratch_required=$(( restored + restored / 4 ))
  log "capacity: artifact_input=${dump_input}B required=${artifact_required}B free(${BACKUP_ROOT})=${free}B"
  log "capacity: scratch_restore=${restored}B required=${scratch_required}B free(${data_dir})=${scratch_free}B"
  log "capacity: whole database is ${logical}B; the difference is index pages and tier-B data, neither of which this artifact carries"
  [ "${free}" -ge "${artifact_required}" ] \
    || die "insufficient free space for the cutover backup: ${free}B free under ${BACKUP_ROOT}, ${artifact_required}B required for a ${dump_input}B included dataset"
  [ "${scratch_free}" -ge "${scratch_required}" ] \
    || die "insufficient free space for the scratch restore: ${scratch_free}B free under ${data_dir}, ${scratch_required}B required to inflate a ${restored}B dataset"

  # The snapshot the artifact and its baseline BOTH read. Opened before the dump
  # and before the baselines, because being one instant is the whole point.
  snapshot_open
  local snapshot_id_used base_counts base_schema base_selected base_connections base_credentials base_assignments
  snapshot_id_used="${SNAPSHOT_ID}"

  log "Reading the rollback baseline under snapshot ${snapshot_id_used}"
  base_counts="$(snapshot_bound table_counts_on "${DB_NAME}")" \
    || die "could not read the table census under the exported snapshot; the rollback artifact cannot be verified and nothing may proceed"
  base_schema="$(snapshot_bound schema_identity_on "${DB_NAME}")" \
    || die "could not read the schema identity under the exported snapshot; the rollback artifact cannot be verified and nothing may proceed"
  base_selected="$(snapshot_bound selected_binding_hash_on "${DB_NAME}")" \
    || die "could not read the selected-binding baseline under the exported snapshot; the rollback artifact cannot be verified and nothing may proceed"
  base_connections="$(snapshot_bound connection_generation_hash_on "${DB_NAME}")" \
    || die "could not read the provider_connections baseline under the exported snapshot; the rollback artifact cannot be verified and nothing may proceed"
  base_credentials="$(snapshot_bound credential_generation_hash_on "${DB_NAME}")" \
    || die "could not read the integration_credentials baseline under the exported snapshot; the rollback artifact cannot be verified and nothing may proceed"
  if counts_have_table "${base_counts}" provider_account_assignments; then
    base_assignments="$(snapshot_bound assignment_hash_on "${DB_NAME}")" \
      || die "could not read the account-assignment baseline under the exported snapshot; the rollback artifact cannot be verified and nothing may proceed"
  else
    base_assignments="absent"
  fi
  [ -n "${base_counts}" ] \
    || die "the table census read under the exported snapshot is empty; the rollback artifact cannot be verified and nothing may proceed"
  snapshot_assert_baseline schema_identity "${base_schema}"
  snapshot_assert_baseline selected_binding_hash "${base_selected}"
  snapshot_assert_baseline connection_generation_hash "${base_connections}"
  snapshot_assert_baseline credential_generation_hash "${base_credentials}"
  snapshot_assert_baseline assignment_hash "${base_assignments}"
  log "baseline under ${snapshot_id_used}: selected=${base_selected} connections=${base_connections} credentials=${base_credentials} assignments=${base_assignments}"

  log "Taking a FRESH full backup of ${DB_NAME} on the database host"
  exclude_flags=""
  while IFS= read -r t; do
    [ -n "${t}" ] || continue
    exclude_flags="${exclude_flags} --exclude-table-data=public.${t}"
  done <<EOF
$(tier_b_table_list)
EOF
  # Redirected, not --file=.
  #
  # The artifact directory is created by this script as root with mode 0700, and
  # pg_dump runs as the postgres user, which cannot create a file inside it:
  # "could not open output file ... Permission denied". Redirecting makes the
  # ROOT shell on the database host create the file and pg_dump merely write to
  # its stdout. The daily backup script already does exactly this, for exactly
  # this reason.
  # Streamed: pg_dump writes to ITS stdout on the database host and ssh carries
  # the bytes here. Nothing large is ever written on the database host.
  # Created 0600 BEFORE the dump streams into it. A bare `>` redirection takes
  # the umask, which left the only complete copy of the production database
  # world-readable. The enclosing directory is 0700, so nothing could reach it —
  # but the file mode is what survives if the directory is ever relaxed, moved,
  # or copied, and every other file this script writes is already 0600.
  : > "${artifact}" && chmod 0600 "${artifact}" \
    || die "could not create ${artifact} on this host"
  # --snapshot: the dump reads the SAME snapshot the baseline above was read
  # under, so "did the artifact come back identical" is a question about the
  # artifact and not about who wrote to the database during the two hours it
  # takes to answer it.
  #
  # 8>&-: the dump must not inherit the write end of the exporter's input FIFO.
  # A pg_dump wedged on an unresponsive database would otherwise keep that FIFO
  # open after this process closed it, and the exporter would not see EOF.
  local dump_err dump_err_text
  dump_err="${SNAPSHOT_WORKDIR}/pg_dump.stderr"
  : > "${dump_err}" 2>/dev/null || dump_err="/dev/null"
  if ! db_run "runuser -u postgres -- pg_dump --dbname=$(printf %q "${DB_NAME}") --snapshot=$(printf %q "${snapshot_id_used}") --format=custom --compress=${BACKUP_COMPRESS_LEVEL} --no-owner --no-privileges --no-tablespaces${exclude_flags}" > "${artifact}" 2>"${dump_err}" 8>&-; then
    dump_err_text="$(tr '\n' ' ' < "${dump_err}" 2>/dev/null || true)"
    case "${dump_err_text}" in
      *"unrecognized option"* | *"invalid option"* | *"unknown option"*)
        die "pg_dump on the database host does not support --snapshot (${dump_err_text}), so the dump and its baseline cannot be bound to one snapshot. This wrapper will NOT fall back to comparing a restored backup against the live database as it stands hours later; that is the comparison that threw a good artifact away in production." ;;
    esac
    die "pg_dump failed (${dump_err_text}); there is no rollback artifact, so nothing may proceed"
  fi

  # Record what this artifact actually cost, so the next cutover sizes itself
  # against a measurement instead of a guess.
  # `wc -c <file` rather than `stat -c %s`: stat's flags differ between GNU and
  # BSD, and this script has to run against both.
  artifact_bytes="$(wc -c < "${artifact}" | tr -d '[:space:]')"
  case "${artifact_bytes}" in
    "" | *[!0-9]*) : ;;
    *) printf 'input_bytes=%s\nartifact_bytes=%s\n' "${dump_input}" "${artifact_bytes}" \
         > "${BACKUP_ROOT}/last-artifact-sizing" || true
       log "capacity: artifact measured ${artifact_bytes}B from a ${dump_input}B input" ;;
  esac

  local artifact_sha artifact_bytes artifact_created
  # Hashed HERE, not on the database host. The dump is streamed back over SSH and
  # lands on this host, so the artifact path does not exist over there at all —
  # hashing remotely returned an EMPTY digest while the run carried on, and the
  # manifest then pinned the artifact to nothing. The shape check below is what
  # makes that failure mode loud instead of silent: an empty or malformed digest
  # compares equal to itself, so a vacuous match is indistinguishable from a real
  # one unless the digest is required to look like a digest.
  # `|| artifact_sha=""` so a failed hash lands in the shape check below and gets
  # named, instead of aborting on errexit with no explanation — or, worse, being
  # swallowed silently the way the remote version was.
  artifact_sha="$(sha256_file "${artifact}" 2>/dev/null | tr -d '[:space:]')" || artifact_sha=""
  artifact_bytes="$(wc -c < "${artifact}" | tr -d '[:space:]')"
  artifact_created="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  case "${artifact_bytes}" in "" | 0 | *[!0-9]*) die "the backup artifact ${artifact} is empty or unreadable" ;; esac
  case "${artifact_sha}" in
    [0-9a-f]*) [ "${#artifact_sha}" -eq 64 ] || die "the backup artifact digest is ${#artifact_sha} characters, not 64; the artifact is not pinned and nothing may proceed" ;;
    *) die "the backup artifact digest is empty or malformed; the artifact is not pinned and nothing may proceed" ;;
  esac
  log "backup artifact bytes=${artifact_bytes} sha256=${artifact_sha}"

  # The artifact is closed and pinned, and the baseline it will be judged
  # against was read before it. NOTHING still needs the exported snapshot, so
  # the transaction goes now rather than at the end of the phase: the scratch
  # restore below takes as long again as the dump did, and there is no reason to
  # pin the database's xmin horizon through it.
  snapshot_release
  log "snapshot ${snapshot_id_used} released; the baseline is recorded and the restore below is compared against IT, never against the live database"

  log "Scratch-restoring that artifact into ${scratch} and reading it back"
  db_run "runuser -u postgres -- dropdb --if-exists $(printf %q "${scratch}")" >/dev/null 2>&1 || true
  # Registered BEFORE it exists, so a createdb that half-succeeds, a restore
  # that is killed and a signal during the read-back all drop it on the way out.
  SCRATCH_DB="${scratch}"
  db_run "runuser -u postgres -- createdb $(printf %q "${scratch}")" \
    || die "could not create the scratch database ${scratch}; an unverified backup is not a rollback plan"
  # Piped, for the same reason the dump is redirected: the artifact lives in a
  # root-only directory, so the postgres user cannot even traverse to it. The
  # ROOT shell reads the file and pg_restore takes it on stdin.
  # Streamed back the other way: the artifact is local, pg_restore is remote.
  if ! db_run "runuser -u postgres -- pg_restore --dbname=$(printf %q "${scratch}") --no-owner --no-privileges --exit-on-error" < "${artifact}"; then
    scratch_db_drop
    die "the fresh backup could NOT be restored. Do not migrate: this release has no rollback."
  fi

  local restored_schema restored_selected restored_connections restored_credentials restored_assignments restored_counts
  restored_schema="$(schema_identity_on "${scratch}")"
  restored_selected="$(selected_binding_hash_on "${scratch}")"
  restored_connections="$(connection_generation_hash_on "${scratch}")"
  restored_credentials="$(credential_generation_hash_on "${scratch}")"
  restored_counts="$(table_counts_on "${scratch}")"
  if counts_have_table "${restored_counts}" provider_account_assignments; then
    restored_assignments="$(assignment_hash_on "${scratch}")"
  else
    restored_assignments="absent"
  fi

  scratch_db_drop

  # Compared against the BASELINE, which was read under the same snapshot the
  # dump was taken under — never against the live database.
  #
  # The live database has moved on by now and is SUPPOSED to have: the whole
  # window between the snapshot and this line is one in which the application is
  # still running. Judging the artifact against that is what threw a good
  # rollback away in production. The question this asks is "did the artifact
  # come back byte-for-byte", and it is now a question with a stable answer.
  #
  # A baseline that could not be read never reaches here: snapshot_assert_baseline
  # already refused. A restored value that could not be read is caught by these
  # same comparisons, because "" never equals a 64-character digest.
  [ "${restored_schema}" = "${base_schema}" ] \
    || die "the restored backup's schema identity (${restored_schema}) differs from the snapshot it was taken under (${base_schema}); the artifact does not describe this database"
  [ "${restored_selected}" = "${base_selected}" ] \
    || die "the restored backup does not reproduce the selected-binding set as of snapshot ${snapshot_id_used} (restored ${restored_selected}, snapshot ${base_selected}); it is not a usable rollback"
  [ "${restored_connections}" = "${base_connections}" ] \
    || die "the restored backup does not reproduce provider_connections as of snapshot ${snapshot_id_used} (restored ${restored_connections}, snapshot ${base_connections}); it is not a usable rollback"
  [ "${restored_credentials}" = "${base_credentials}" ] \
    || die "the restored backup does not reproduce integration_credentials as of snapshot ${snapshot_id_used} (restored ${restored_credentials}, snapshot ${base_credentials}); it is not a usable rollback"
  [ "${restored_assignments}" = "${base_assignments}" ] \
    || die "the restored backup does not reproduce the account assignments as of snapshot ${snapshot_id_used} (restored ${restored_assignments}, snapshot ${base_assignments}); it is not a usable rollback"

  local credential_count assignment_count connection_count binding_count
  credential_count="$(printf '%s\n' "${base_counts}" | awk -F= '$1=="integration_credentials"{print $2}')"
  assignment_count="$(printf '%s\n' "${base_counts}" | awk -F= '$1=="provider_account_assignments"{print $2}')"
  connection_count="$(printf '%s\n' "${base_counts}" | awk -F= '$1=="provider_connections"{print $2}')"
  binding_count="$(printf '%s\n' "${base_counts}" | awk -F= '$1=="business_provider_accounts"{print $2}')"

  {
    printf 'cutover_epoch=%s\n' "${epoch}"
    printf 'deploy_sha=%s\n' "${EXPECTED_SHA}"
    printf 'db_name=%s\n' "${DB_NAME}"
    printf 'db_system_identifier=%s\n' "$(db_system_identifier)"
    printf 'artifact_path=%s\n' "${artifact}"
    printf 'artifact_sha256=%s\n' "${artifact_sha}"
    printf 'artifact_bytes=%s\n' "${artifact_bytes}"
    printf 'artifact_created_utc=%s\n' "${artifact_created}"
    printf 'backup_scope=full_database\n'
    # The hashes below describe the ARTIFACT, not the database at the moment the
    # manifest was written. They were read under `snapshot_id`, which is the
    # snapshot pg_dump read, so a reader of this manifest is looking at what a
    # restore of this artifact will actually produce.
    printf 'snapshot_id=%s\n' "${snapshot_id_used}"
    printf 'baseline_source=exported_snapshot\n'
    printf 'schema_identity=%s\n' "${base_schema}"
    printf 'selected_binding_hash=%s\n' "${base_selected}"
    printf 'connection_generation_hash=%s\n' "${base_connections}"
    printf 'credential_generation_hash=%s\n' "${base_credentials}"
    printf 'assignment_hash=%s\n' "${base_assignments}"
    printf 'binding_count=%s\n' "${binding_count:-absent}"
    printf 'connection_count=%s\n' "${connection_count:-absent}"
    printf 'credential_count=%s\n' "${credential_count:-absent}"
    printf 'assignment_count=%s\n' "${assignment_count:-absent}"
    printf 'scratch_restore_db=%s\n' "${scratch}"
    printf 'scratch_restore_verified=yes\n'
  } > "${manifest}.tmp"
  # Written HERE, beside the artifact it describes, because that is where every
  # reader of it runs: assert_backup_manifest stats artifact_path locally and
  # hashes the manifest locally. Writing it over the SSH link put it on the
  # database host — a directory of the same name existed there, so the write
  # succeeded and left the app host with an artifact and no manifest. Atomic
  # rename and 0600 for the same reason as the release identity record: a
  # half-written manifest must never be readable as a whole one.
  chmod 0600 "${manifest}.tmp"
  mv "${manifest}.tmp" "${manifest}"
  chmod 0600 "${manifest}"

  BACKUP_MANIFEST="${manifest}"
  log "verified rollback artifact: ${artifact} (${artifact_bytes}B), manifest ${manifest}"
}

backup_manifest_value() {
  printf '%s\n' "$1" | awk -F= -v key="$2" '$1 == key { sub(/^[^=]*=/, ""); print; exit }'
}

# A manifest is only a rollback plan for THIS cutover of THIS database. Stale
# (an earlier epoch), foreign (another database or another system identifier) or
# tampered (a digest that no longer matches what the state record pinned) must
# all refuse.
assert_backup_manifest_bound() {
  local manifest_path text manifest_sha
  manifest_path="$(state_get backup_manifest_path)"
  [ -n "${manifest_path}" ] || die "the state record pins no backup manifest; re-run preflight"
  text="$(read_manifest_file "${manifest_path}" 2>/dev/null || true)"
  [ -n "${text}" ] || die "the backup manifest ${manifest_path} is gone from the database host; the rollback artifact this cutover was authorised against no longer exists"
  manifest_sha="$(printf '%s' "${text}" | sha256_stdin)"
  [ "${manifest_sha}" = "$(state_get backup_manifest_sha256)" ] \
    || die "the backup manifest changed since preflight (${manifest_sha} vs $(state_get backup_manifest_sha256)); it is not the artifact this cutover was authorised against"
  [ "$(backup_manifest_value "${text}" cutover_epoch)" = "$(state_get cutover_epoch)" ] \
    || die "the backup manifest belongs to cutover epoch $(backup_manifest_value "${text}" cutover_epoch), not $(state_get cutover_epoch); it is stale"
  [ "$(backup_manifest_value "${text}" db_name)" = "${DB_NAME}" ] \
    || die "the backup manifest describes database $(backup_manifest_value "${text}" db_name), not ${DB_NAME}"
  [ "$(backup_manifest_value "${text}" db_system_identifier)" = "$(db_system_identifier)" ] \
    || die "the backup manifest describes system identifier $(backup_manifest_value "${text}" db_system_identifier); this database reports $(db_system_identifier). It is a foreign backup."
  [ "$(backup_manifest_value "${text}" scratch_restore_verified)" = "yes" ] \
    || die "the backup manifest does not record a completed scratch restore"
  # The artifact is checksummed once, when it is taken. Re-checksumming a
  # multi-gigabyte dump at every phase would add minutes to each step, so later
  # phases prove it still exists at exactly the recorded size instead, and say so.
  local artifact bytes
  artifact="$(backup_manifest_value "${text}" artifact_path)"
  bytes="$(wc -c < "${artifact}" 2>/dev/null | tr -d '[:space:]' || true)"
  [ -n "${bytes}" ] || die "the rollback artifact ${artifact} is missing from this host"
  [ "${bytes}" = "$(backup_manifest_value "${text}" artifact_bytes)" ] \
    || die "the rollback artifact is ${bytes}B, the manifest recorded $(backup_manifest_value "${text}" artifact_bytes)B; it was replaced or truncated"
  log "rollback artifact bound: epoch=$(state_get cutover_epoch) ${artifact} (${bytes}B, size re-checked; digest verified at preflight)"
}

# ── The fingerprint host and the runtime must be the same database ─────────
#
# `db_sql` reaches the database through SYNC_CUTOVER_DB_SSH/DB_NAME; the app
# reaches it through DATABASE_URL in .env.production. Nothing proved those were
# the same system. A cutover could fingerprint one database, migrate it, and
# leave the runtime pointed at another.
assert_runtime_database_matches() {
  local runtime_identity control_identity
  control_identity="$(db_identity)"
  [ -n "${control_identity}" ] || die "could not read the control-path database identity"
  runtime_identity="$(
    docker run --rm --network host --env-file "${ENV_FILE}" \
      --entrypoint /bin/sh "${EXPECTED_WEB_IMAGE}" -c '
        node -e "
          const { Client } = require(\"pg\");
          const client = new Client({ connectionString: process.env.DATABASE_URL });
          client.connect()
            .then(() => client.query(\"SELECT current_database() || chr(124) || system_identifier::text AS id FROM pg_control_system()\"))
            .then((r) => { process.stdout.write(r.rows[0].id); return client.end(); })
            .catch((e) => { process.stderr.write(String(e && e.message)); process.exit(1); });
        "' 2>/dev/null | tr -d '[:space:]'
  )"
  [ -n "${runtime_identity}" ] \
    || die "could not read the database identity through the runtime's DATABASE_URL"
  [ "${runtime_identity}" = "${control_identity}" ] \
    || die "the cutover control path (${control_identity}) and the runtime DATABASE_URL (${runtime_identity}) point at DIFFERENT databases"
  log "runtime and control path agree: ${control_identity}"
}

# ── Quiescence, measured on the database ───────────────────────────────────
#
# Counting rows whose `lease_owner` is not null counts leases that expired days
# ago and will never clear, so the old gate could wait forever on nothing while
# a live backend held an open transaction it never looked at. What actually
# matters is whether an application backend is attached to THIS database right
# now, and whether anything holds a transaction open across the migration.
active_app_backends() {
  db_sql "
    SELECT COALESCE(string_agg(
             pid::text || '|' || COALESCE(application_name, '') || '|' || COALESCE(state, '') ||
             '|' || COALESCE(backend_start::text, ''), E'\n' ORDER BY pid), '')
    FROM pg_stat_activity
    WHERE datname = current_database()
      AND pid <> pg_backend_pid()
      AND backend_type = 'client backend'
      AND (
        application_name LIKE '${APP_NAME_PREFIX}%'
        OR state IN ('idle in transaction', 'idle in transaction (aborted)')
      );
  "
}

prepared_transactions() {
  db_sql "SELECT count(*)::text FROM pg_prepared_xacts WHERE database = current_database();" |
    tr -d '[:space:]'
}

# Scheduled units ON THE DATABASE HOST that write to the production database.
#
# The app-side scheduler is stopped by name and the application containers are
# stopped by name, and neither of those is the whole set of writers. A systemd
# timer on the database host runs as `postgres`, so it carries no application
# name and `active_app_backends` cannot see it; it connects, writes and
# disconnects between two polls, so a point-in-time session check will usually
# miss it too.
#
# It is not hypothetical. adsecute-db-healthcheck.timer fires every 15 minutes
# and appends to system_capacity_snapshots. During a 90-minute restore of the
# production database it inserted five rows into a table pg_restore was still
# loading, and the restore died adding the primary key back:
#
#   could not create unique index "system_capacity_snapshots_pkey"
#   DETAIL: Key (id)=(1) is duplicated.
#
# Quiescence that a background writer can walk straight through is not
# quiescence. This refuses rather than stopping the unit itself: taking
# ownership of units on the other host means restoring them later, and a
# cutover that silently starts and stops things on a machine it does not
# otherwise manage is worse than one that stops and says why.
db_host_active_adsecute_timers() {
  # Pick the field that ENDS in .timer rather than a fixed column. The last
  # column of `list-timers` is ACTIVATES — the .service — and a timer-activated
  # oneshot service reads `inactive` between firings, so asking about the
  # service would report "nothing running" for a timer that is armed and will
  # fire again in nine minutes. Column positions also shift with the width of
  # the elapsed-time fields, so counting from either end is not safe.
  db_run "systemctl list-timers --all --no-legend --no-pager 2>/dev/null | awk '{for (i = 1; i <= NF; i++) if (\$i ~ /\\.timer\$/) print \$i}' | grep -i adsecute || true" \
    | while IFS= read -r unit; do
        [ -n "${unit}" ] || continue
        if [ "$(db_run "systemctl is-active $(printf %q "${unit}") 2>/dev/null || true" | tr -d '[:space:]')" = "active" ]; then
          printf '%s\n' "${unit}"
        fi
      done
}

# ── Continuation across releases, once production is already migrated ──────
#
# ATTESTATION_DIR holds one record per cutover that reached fingerprint-post.
# It is the only thing that can license a no-op migration, so it is written by
# the phase that proved the schema, not by an operator, and it is 0600 like
# every other record here.
ATTESTATION_DIR="${SYNC_CUTOVER_ATTESTATION_DIR:-${STATE_DIR}/attestations}"

write_migration_attestation() {
  local epoch="$1" schema="$2" plaintext="$3" tmp file
  mkdir -p "${ATTESTATION_DIR}" && chmod 0700 "${ATTESTATION_DIR}"
  file="${ATTESTATION_DIR}/${epoch}"
  tmp="$(mktemp "${ATTESTATION_DIR}/att.XXXXXX")"
  chmod 0600 "${tmp}"
  {
    printf 'attestation_version=1\n'
    printf 'cutover_epoch=%s\n' "${epoch}"
    printf 'deploy_sha=%s\n' "${EXPECTED_SHA}"
    printf 'db_identity=%s\n' "$(db_identity)"
    printf 'schema_identity_post=%s\n' "${schema}"
    printf 'plaintext_secrets_after=%s\n' "${plaintext}"
    printf 'verify_contract_passed=yes\n'
    printf 'attested_utc=%s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  } > "${tmp}"
  mv "${tmp}" "${file}"
  chmod 0600 "${file}"
  log "migration attestation written to ${file} (schema ${schema})"
}

# How many credential rows still hold a plaintext secret. Zero is the only
# acceptable answer after the encryption migration, and it is re-proved on every
# continuation rather than assumed to have stayed true.
plaintext_secret_count() {
  db_sql "
    SELECT COALESCE(SUM(n), 0)::text FROM (
      SELECT COUNT(*) AS n FROM integration_credentials
       WHERE COALESCE(to_jsonb(integration_credentials) ->> 'access_token', '') <> ''
         AND to_jsonb(integration_credentials) ->> 'access_token' NOT LIKE 'enc:v1:%'
      UNION ALL
      SELECT COUNT(*) AS n FROM integration_credentials
       WHERE COALESCE(to_jsonb(integration_credentials) ->> 'refresh_token', '') <> ''
         AND to_jsonb(integration_credentials) ->> 'refresh_token' NOT LIKE 'enc:v1:%'
    ) s;
  " | tr -d '[:space:]'
}

assert_continuation_attestation() {
  local current_schema="$1" prior file prior_schema prior_db prior_version prior_plaintext now_plaintext

  prior="${SYNC_CUTOVER_CONTINUES_FROM:-}"
  [ -n "${prior}" ] || die "the schema identity is unchanged (${current_schema}) and no prior cutover was named. Either the migration this cutover exists to apply did not run, or this release genuinely carries no schema change — in which case set SYNC_CUTOVER_CONTINUES_FROM to the epoch of the cutover that DID apply it, so the claim can be checked instead of believed."

  case "${prior}" in
    *[!A-Za-z0-9._-]*) die "SYNC_CUTOVER_CONTINUES_FROM='${prior}' is not an epoch name" ;;
  esac
  file="${ATTESTATION_DIR}/${prior}"
  [ -f "${file}" ] || die "no attestation for cutover '${prior}' at ${file}; a continuation can only be authorised by a cutover that actually reached fingerprint-post on this host"

  prior_version="$(awk -F= '$1=="attestation_version"{print $2}' "${file}" | tr -d '[:space:]')"
  [ "${prior_version}" = "1" ] \
    || die "attestation ${file} is version '${prior_version}', this wrapper reads version 1"

  prior_schema="$(awk -F= '$1=="schema_identity_post"{print $2}' "${file}" | tr -d '[:space:]')"
  [ "${prior_schema}" = "${current_schema}" ] \
    || die "cutover '${prior}' attested schema ${prior_schema}; this database is ${current_schema}. The schema moved since that cutover, so its attestation cannot license this one — something migrated outside a cutover."

  prior_db="$(awk -F= '$1=="db_identity"{print $2}' "${file}" | tr -d '[:space:]')"
  [ "${prior_db}" = "$(db_identity)" ] \
    || die "cutover '${prior}' attested database ${prior_db}; this is $(db_identity). That attestation describes a different system."

  # The encryption migration's outcome is re-proved, not inherited. An
  # attestation says what WAS true; this says what is true now.
  prior_plaintext="$(awk -F= '$1=="plaintext_secrets_after"{print $2}' "${file}" | tr -d '[:space:]')"
  now_plaintext="$(plaintext_secret_count)"
  [ "${now_plaintext}" = "0" ] \
    || die "${now_plaintext} credential row(s) hold a plaintext secret. The prior cutover attested ${prior_plaintext}; plaintext has come back, so this database is not in the state that attestation describes."

  log "continuation authorised by cutover ${prior}: schema ${current_schema} is byte-identical to the one it attested, same database, and ${now_plaintext} plaintext secrets remain. The migration ran and correctly changed nothing."
  state_set continues_from "${prior}"
  release_set continues_from "${prior}"
}

assert_database_quiescent() {
  local backends prepared foreign timers
  backends="$(active_app_backends)"
  if [ -n "$(printf '%s' "${backends}" | tr -d '[:space:]')" ]; then
    printf '%s\n' "${backends}" >&2
    die "quiescence not reached: ${APP_NAME_PREFIX} backends are still attached to ${DB_NAME} (pid|application_name|state|backend_start listed above). Stop them; do not migrate underneath them."
  fi
  prepared="$(prepared_transactions)"
  [ "${prepared}" = "0" ] \
    || die "quiescence not reached: ${prepared} prepared transaction(s) on ${DB_NAME} hold locks that will block every DDL statement in the migration"

  # Anything at all besides this cutover's own connection. Named backends are
  # only the writers we happen to recognise; this is the ones we do not.
  foreign="$(db_sql "
    SELECT count(*) FROM pg_stat_activity
    WHERE datname = current_database()
      AND pid <> pg_backend_pid()
      AND backend_type = 'client backend';
  " | tr -d '[:space:]')"
  [ "${foreign}" = "0" ] \
    || die "quiescence not reached: ${foreign} other client backend(s) are attached to ${DB_NAME}. They carry no ${APP_NAME_PREFIX} application name, so they are something this cutover does not manage — find them before migrating."

  timers="$(db_host_active_adsecute_timers)"
  if [ -n "$(printf '%s' "${timers}" | tr -d '[:space:]')" ]; then
    printf '%s\n' "${timers}" >&2
    die "quiescence not reached: the timer(s) listed above are ACTIVE on the database host and write to ${DB_NAME} between polls. Stop them for the duration (systemctl stop <unit>) and start them again when the cutover is done; leaving them running corrupts a restore rather than merely racing it."
  fi

  log "database quiescent: no ${APP_NAME_PREFIX} client backends, no other client backends, no prepared transactions, no active adsecute timers on the database host"
}

# ── State invariants ───────────────────────────────────────────────────────

env_file_hash() { sha256_file "${ENV_FILE}"; }

assert_state_invariants() {
  local recorded
  [ "$(state_get state_version)" = "${STATE_VERSION}" ] \
    || die "the state record is version '$(state_get state_version)', this wrapper writes version ${STATE_VERSION}; the two do not describe the same cutover. Start from preflight."
  [ "$(state_get deploy_sha)" = "${EXPECTED_SHA}" ] \
    || die "this cutover was opened for $(state_get deploy_sha); DEPLOY_SHA is now ${EXPECTED_SHA}. One state directory cannot hold two releases."
  assert_image_pin
  recorded="$(db_identity)"
  [ "${recorded}" = "$(state_get db_identity)" ] \
    || die "the database identity is now ${recorded}, the cutover was opened against $(state_get db_identity); the control path was repointed mid-cutover"
  recorded="$(env_file_hash)"
  [ "${recorded}" = "$(state_get env_file_sha256)" ] \
    || die "${ENV_FILE} changed outside this cutover (${recorded} vs $(state_get env_file_sha256)). Reconcile by hand; the recreate would deploy an unreviewed configuration."
  [ "${SCHEDULER}" = "$(state_get scheduler_spec)" ] \
