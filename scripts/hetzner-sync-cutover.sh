# ── F21.6: the fingerprint ─────────────────────────────────────────────────
#
# Three row counts could not tell an expand-only migration from one that swapped
# one selected account for another, rotated a credential, dropped a connection or
# rewrote the release-gate history: all of those keep the counts identical. The
# fingerprint below is the full selected identity/position set, the connection
# and credential GENERATIONS (hashed — no token, no secret, ever leaves the
# database), the counts and content hashes of the raw/config/state/release-gate
# relations that exist, the migration schema identity, and the exact database id.

FINGERPRINT_TABLES="business_provider_accounts provider_connections integration_credentials provider_account_assignments provider_accounts meta_raw_snapshots shopify_raw_snapshots google_ads_raw_snapshots meta_config_snapshots meta_sync_state google_ads_sync_state shopify_sync_state sync_release_gates sync_runtime_instances sync_worker_heartbeats"

db_identity() {
  db_sql "SELECT current_database() || '|' || system_identifier::text FROM pg_control_system();" |
    tr -d '[:space:]'
}

db_system_identifier() {
  db_sql "SELECT system_identifier::text FROM pg_control_system();" | tr -d '[:space:]'
}

# The migration schema identity. There is no migration ledger table — migrations
# are idempotent DDL replayed every deploy — so schema identity has to come from
# the catalogue itself.
schema_identity_on() {
  db_sql_on "$1" "
    SELECT encode(sha256(convert_to(COALESCE(string_agg(sig, E'\n' ORDER BY sig), ''), 'UTF8')), 'hex')
    FROM (
      SELECT c.table_name || ':' || c.column_name || ':' || c.data_type || ':' || c.is_nullable AS sig
      FROM information_schema.columns c
      JOIN information_schema.tables t
        ON t.table_schema = c.table_schema AND t.table_name = c.table_name
      WHERE c.table_schema = 'public' AND t.table_type = 'BASE TABLE'
    ) s;
  " | tr -d '[:space:]'
}

# One round trip for every count, over exactly the relations that exist. A
# missing relation is reported as missing rather than aborting the statement,
# because the pre-migration and post-migration schemas legitimately differ.
table_counts_on() {
  local database="$1" values="" table
  for table in ${FINGERPRINT_TABLES}; do
    if [ -z "${values}" ]; then values="('${table}')"; else values="${values},('${table}')"; fi
  done
  db_sql_on "${database}" "
    WITH wanted(relname) AS (VALUES ${values})
    SELECT w.relname || '=' ||
           (xpath('/row/c/text()',
                  query_to_xml('SELECT count(*) AS c FROM public.' || quote_ident(w.relname),
                               false, true, '')))[1]::text
    FROM wanted w
    WHERE to_regclass('public.' || quote_ident(w.relname)) IS NOT NULL
    ORDER BY w.relname;
  "
}

# OLD-SCHEMA SAFE. `is_selected` is added BY the migration this cutover runs, so
# before it exists the query would fail and the pre-fingerprint could never be
# taken — the deadlock this phase graph exists to avoid. Before the column
# exists, the pre-model semantics are that every identity binding IS selected,
# so that is what gets hashed; after the migration the backfilled selected set
# must reproduce exactly the same digest.
selected_binding_hash_on() {
  db_sql_on "$1" "
    SELECT COALESCE(encode(sha256(convert_to(string_agg(identity, E'\n' ORDER BY identity), 'UTF8')), 'hex'), 'empty')
    FROM (
      SELECT bpa.business_id::text || '|' || bpa.provider || '|' || bpa.provider_account_id || '|' ||
             COALESCE(to_jsonb(bpa) ->> 'position', 'null') AS identity
      FROM business_provider_accounts bpa
      WHERE CASE
              WHEN EXISTS (
                SELECT 1 FROM information_schema.columns
                WHERE table_schema = current_schema()
                  AND table_name = 'business_provider_accounts'
                  AND column_name = 'is_selected'
              )
              THEN COALESCE((to_jsonb(bpa) ->> 'is_selected')::boolean, FALSE)
              ELSE TRUE
            END
    ) rows;
  " | tr -d '[:space:]'
}

connection_generation_hash_on() {
  db_sql_on "$1" "
    SELECT COALESCE(encode(sha256(convert_to(string_agg(sig, E'\n' ORDER BY sig), 'UTF8')), 'hex'), 'empty')
    FROM (
      SELECT pc.business_id::text || '|' || pc.provider || '|' ||
             COALESCE(to_jsonb(pc) ->> 'status', '') || '|' ||
             COALESCE(to_jsonb(pc) ->> 'provider_account_id', '') || '|' ||
             COALESCE(to_jsonb(pc) ->> 'updated_at', '') AS sig
      FROM provider_connections pc
    ) s;
  " | tr -d '[:space:]'
}

# The credential GENERATION, never the credential. Each token is reduced to its
# own digest before it is folded into the set digest, so a rotation is visible
# and the secret is not — including to anyone reading this script's output or
# the state directory.
credential_generation_hash_on() {
  db_sql_on "$1" "
    SELECT COALESCE(encode(sha256(convert_to(string_agg(sig, E'\n' ORDER BY sig), 'UTF8')), 'hex'), 'empty')
    FROM (
      SELECT ic.provider_connection_id::text || '|' ||
             encode(sha256(convert_to(
               COALESCE(to_jsonb(ic) ->> 'access_token', '') || '|' ||
               COALESCE(to_jsonb(ic) ->> 'refresh_token', ''), 'UTF8')), 'hex') || '|' ||
             COALESCE(to_jsonb(ic) ->> 'updated_at', '') AS sig
      FROM integration_credentials ic
    ) s;
  " | tr -d '[:space:]'
}

# A per-row credential census, so that a CHANGE in credential_generation_hash can
# be explained instead of merely detected.
#
# The generation hash is one opaque digest over every row. That is the right
# shape for "did anything move", and it is useless for "was the thing that moved
# the thing we intended to move" — an intended plaintext -> ciphertext rewrite and
# a corrupted token produce the same answer: different.
#
# This emits, per row, the shape of each secret and a digest OF each secret. No
# secret value is printed; a sha256 is not the token, and the generation hash
# already digests the same material. Ordered by id so the two sides are
# line-comparable.
credential_census_on() {
  db_sql_on "$1" "
    SELECT ic.id::text || '|' ||
           ic.provider_connection_id::text || '|' ||
           CASE WHEN COALESCE(to_jsonb(ic) ->> 'access_token', '') = '' THEN 'empty'
                WHEN to_jsonb(ic) ->> 'access_token' LIKE 'enc:v1:%' THEN 'enc'
                ELSE 'plain' END || '|' ||
           CASE WHEN COALESCE(to_jsonb(ic) ->> 'refresh_token', '') = '' THEN 'empty'
                WHEN to_jsonb(ic) ->> 'refresh_token' LIKE 'enc:v1:%' THEN 'enc'
                ELSE 'plain' END || '|' ||
           CASE WHEN COALESCE(to_jsonb(ic) ->> 'access_token', '') = '' THEN '-'
                ELSE encode(sha256(convert_to(to_jsonb(ic) ->> 'access_token', 'UTF8')), 'hex') END || '|' ||
           CASE WHEN COALESCE(to_jsonb(ic) ->> 'refresh_token', '') = '' THEN '-'
                ELSE encode(sha256(convert_to(to_jsonb(ic) ->> 'refresh_token', 'UTF8')), 'hex') END || '|' ||
           COALESCE(to_jsonb(ic) ->> 'updated_at', '')
    FROM integration_credentials ic
    ORDER BY ic.id::text;
  "
}

# Accept a credential_generation_hash change ONLY when every difference is a
# plaintext secret becoming ciphertext. Anything else is refused.
#
# Permitted, per row and per column: plain -> enc.
# Refused: a row appearing or disappearing; provider_connection_id or updated_at
# moving; enc -> plain; enc -> a DIFFERENT ciphertext digest (a re-encryption or
# a corruption is not a conversion); plain -> plain; empty gaining a value or a
# value becoming empty. A run that ends with any plaintext left is refused, and
# so is one where nothing actually converted — then the hash moved for a reason
# this rule cannot see, which is exactly when it must not be waved through.
assert_credential_change_is_encryption_only() {
  local pre="$1" post="$2" verdict
  verdict="$(awk -F'|' '
    function fail(msg) { print "VIOLATION " msg; violations++ }
    NR == FNR {
      pre_conn[$1] = $2; pre_a[$1] = $3; pre_r[$1] = $4
      pre_ad[$1] = $5; pre_rd[$1] = $6; pre_up[$1] = $7
      pre_seen[$1] = 1; next
    }
    {
      id = $1
      if (!(id in pre_seen)) { fail("row " id " did not exist before the migration"); next }
      post_seen[id] = 1
      if ($2 != pre_conn[id]) fail("row " id " changed provider_connection_id")
      if ($7 != pre_up[id])   fail("row " id " changed updated_at")
      # access
      if (pre_a[id] == "plain" && $3 == "enc") converted++
      else if (pre_a[id] == $3 && pre_ad[id] == $5) ;
      else fail("row " id " access_token " pre_a[id] "->" $3 " is not a plaintext-to-ciphertext conversion")
      # refresh
      if (pre_r[id] == "plain" && $4 == "enc") converted++
      else if (pre_r[id] == $4 && pre_rd[id] == $6) ;
      else fail("row " id " refresh_token " pre_r[id] "->" $4 " is not a plaintext-to-ciphertext conversion")
      if ($3 == "plain" || $4 == "plain") fail("row " id " still holds a plaintext secret after the migration")
    }
    END {
      for (id in pre_seen) if (!(id in post_seen)) fail("row " id " disappeared during the migration")
      if (violations > 0) { print "REFUSED " violations; exit 0 }
      if (converted == 0) { print "REFUSED unexplained"; exit 0 }
      print "CONVERTED " converted
    }
  ' "${pre}" "${post}")"

  # `|| true` on both: finding no VIOLATION lines is the SUCCESS case, and under
  # `set -o pipefail` a grep that matches nothing makes the whole pipeline
  # non-zero, which `set -e` then turns into a silent exit with no diagnosis at
  # all — the phase would appear to fail for no stated reason precisely when the
  # credentials were fine.
  printf '%s\n' "${verdict}" | { grep '^VIOLATION ' || true; } | while IFS= read -r line; do
    log "credential census: ${line#VIOLATION }"
  done

  case "$(printf '%s\n' "${verdict}" | grep -E '^(CONVERTED|REFUSED) ' || true)" in
    "CONVERTED "*)
      log "credential_generation_hash moved because $(printf '%s\n' "${verdict}" | awk '/^CONVERTED /{print $2}') plaintext secret(s) became ciphertext; every other credential byte, connection binding and updated_at is unchanged"
      return 0 ;;
    "REFUSED unexplained")
      die "credential_generation_hash changed but NO plaintext secret was converted; the change is unexplained. Do not enable." ;;
    *)
      die "credential_generation_hash changed in ways that are not a plaintext-to-ciphertext conversion (see the census violations above). Do not enable." ;;
  esac
}

