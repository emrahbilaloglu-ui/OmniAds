#!/usr/bin/env bash
set -euo pipefail

# Host-side global sync cutover.
#
# WHY THIS EXISTS
#
# `scripts/global-sync-rollout.ts` is TypeScript run through npm. The app host
# has docker and docker compose and no Node, no npm, no node_modules — so
# `npm run rollout:enable` cannot run there. Everything below uses what the hosts
# actually have and reaches the repository's TypeScript by executing it inside
# the already-pinned worker image.
#
# HOW THIS FILE GETS TO THE APP HOST
#
# It does not arrive by magic and it is not in a git checkout on the host: the
# deploy only ever synced `docker-compose.yml`, so the runbook used to name a
# repository path that does not exist there.
#
# This file therefore lives under `scripts/`, which the worker image already
# copies (`COPY --from=builder /app/scripts /app/scripts`), so the release image
# carries it at `/app/scripts/hetzner-sync-cutover.sh` with no build-context
# special case. It used to live under `.github/`, which `.dockerignore` excludes,
# and reached the image only as a generated byte-identical duplicate — a second
# copy of a security-critical script, kept honest by a drift gate. Moving the
# file deleted the duplicate and the gate that guarded it.
#
# `scripts/cutover-wrapper-package.sh` records this file's SHA-256 in
# `scripts/cutover-wrapper.manifest`, which ships in the same image directory.
# `.github/scripts/hetzner-remote.sh deliver_cutover_wrapper` extracts both out
# of the exact pinned image, refuses unless the extracted script hashes to what
# the manifest pins, and installs them under `${APP_DIR}/cutover`.
# `assert_wrapper_integrity` below then re-hashes THIS FILE against that manifest
# before any phase runs, so a wrapper that was edited on the host, truncated by a
# failed copy, or carried over from another release refuses instead of driving a
# cutover nobody reviewed.
#
# TWO HOSTS
#
# The application and PostgreSQL are on SEPARATE hosts. The app host has the
# Compose project and no local PostgreSQL socket; the DB host has PostgreSQL and
# no Compose project. Assuming both live together is how a cutover script fails
# on its first real run. Every database operation therefore goes through
# `db_sql`/`db_run`, which use `SYNC_CUTOVER_DB_SSH` when set and fall back to a
# local psql only for single-host development.
#
# PHASE GRAPH
#
# Preflight is OLD-SCHEMA SAFE — it checks images, the env file, a freshly taken
# and scratch-restored backup, the scheduler and the database identity, none of
# which depend on the new schema — and the post-migration schema contract is its
# own phase AFTER migrate. A preflight that ran the post-migration contract could
# never pass before the migration it gates, which is a deadlock, not a gate.
#
# WHAT IS AND IS NOT ATOMIC
#
# Nothing here is atomic across hosts, and this file does not pretend otherwise.
# What is actually guaranteed:
#   - the env file is REPLACED by a rename within one filesystem, so a reader
#     sees either the whole old file or the whole new file, never a partial one;
#   - the previous (disabled) env file is copied aside first, so the disabled
#     configuration can always be put back byte-for-byte;
#   - the root crontab is replaced as a whole document, so the managed block and
#     every unrelated entry move together.
# What is NOT guaranteed:
#   - the RUNTIME does not change when the file changes. web and worker read
#     their environment when the container is created, so the runtime change is
#     the recreate, and the recreate is sequential: for a window measured in
#     seconds one container runs the new configuration and the other the old.
#     The cutover is built around both processes already being deployed and
#     disabled before that window opens, and around a failure inside the window
#     restoring the disabled env, stopping everything and invalidating the state
#     so the only way forward is a clean retry;
#   - a database migration is not undone by any of this. The rollback of record
#     is the backup artifact this script takes and scratch-restores.
#
#   ./hetzner-sync-cutover.sh <phase>
#
# Phases, in order:
#   preflight         old-schema safe; images, env, FRESH verified backup, scheduler, DB
#   quiesce           stop the real scheduler, autoheal, web, worker; prove drain
#   fingerprint-pre   DB identity, schema identity, counts, identity/generation hashes
#   migrate           run migrations from the pinned image
#   verify-contract   POST-migration schema contract (needs the new schema)
#   fingerprint-post  compare against the pre-migration fingerprint
#   deploy-disabled   both processes on the new build with every lane off
#   enable            update the preserved env, recreate both, verify, roll back on failure
#   resume-scheduler  re-enable the real scheduler, last
#   emergency-disable stop live runtime and scheduler; INVALIDATE the enable proof
#   status            print the state record and live state

PHASE="${1:-status}"
APP_DIR="${REMOTE_APP_DIR:-/var/www/adsecute}"
ENV_FILE="${APP_DIR}/.env.production"
STATE_DIR="${SYNC_CUTOVER_STATE_DIR:-/var/lib/adsecute-cutover}"
# The versioned state RECORD. The previous append-only list of phase strings
# could not answer "is this the same cutover?" — it survived a retag, an env
# edit, a different DEPLOY_SHA and an emergency stop, and every one of those
# leaves the recorded phases meaningless.
STATE_FILE="${STATE_DIR}/state"
STATE_VERSION=2
IMAGE_PIN_FILE="${STATE_DIR}/image-pin"
LOCK_FILE="${STATE_DIR}/lock"

CUTOVER_DIR="${SYNC_CUTOVER_INSTALL_DIR:-${APP_DIR}/cutover}"
WRAPPER_MANIFEST="${SYNC_CUTOVER_WRAPPER_MANIFEST:-${CUTOVER_DIR}/cutover-wrapper.manifest}"

# Where the FRESH cutover backup and its manifest are written ON THE DB HOST.
# Where the rollback artifact is written.
#
# On the APP host, not the database host, and that is deliberate twice over.
#
# Capacity: the database host's root filesystem has ~31 GiB free and also holds
# the /srv tablespace carrying 36 GiB of live indexes. A tier-A artifact of this
# database is ~33 GiB, because tier A now includes the raw-snapshot pair whose
# 37 GiB of TOAST is already compressed by PostgreSQL and does not shrink again.
# Writing it there fills the filesystem the indexes need to extend into — which
# is a production incident, not a failed backup. Measured: 239 MiB/min against
# 17 GiB free, ~73 minutes to full.
#
# Independence: a rollback artifact stored on the same machine as the data it
# protects is one hardware failure from being useless. The app host is a
# different machine with 63 GiB free.
BACKUP_ROOT="${SYNC_CUTOVER_BACKUP_ROOT:-/var/backups/adsecute-cutover}"

# Compression level for the rollback artifact.
#
# NOT 9. Measured on this database: pg_dump sat at 85.6% CPU and produced
# 64 MiB/min, which is ~8.5 hours for a ~33 GiB artifact. The bulk of tier A is
# raw-snapshot TOAST that PostgreSQL has ALREADY compressed, so level 9 spends
# enormous CPU re-compressing incompressible bytes for almost no size gain.
#
# A rollback artifact is short-lived and its value is being ready quickly. A low
# level is many times faster and, on this data, very nearly the same size.
BACKUP_COMPRESS_LEVEL="${SYNC_CUTOVER_BACKUP_COMPRESS:-1}"
BACKUP_MANIFEST="${SYNC_CUTOVER_BACKUP_MANIFEST:-}"

DRAIN_SECONDS="${SYNC_CUTOVER_DRAIN_SECONDS:-90}"
DB_NAME="${DB_NAME:-adsecute_prod}"

# The DB host. Empty means "PostgreSQL is reachable locally", which is only true
# in development.
DB_SSH="${SYNC_CUTOVER_DB_SSH:-}"

# One multiplexed connection for the whole cutover, not one per statement.
#
# A cutover issues dozens of separate database calls. Opening a fresh SSH
# connection for each one is fine on a quiet host and fails on a busy one: the
# database host runs `sshd` with a MaxStartups limit, and internet-facing brute
# force traffic keeps that queue full, so an unlucky connection is dropped and
# the phase dies mid-backup. Observed exactly that: "drop connection ... past
# MaxStartups" while taking the rollback artifact.
#
# ControlMaster reuses a single authenticated channel, so the whole cutover
# costs one connection attempt instead of dozens. ControlPersist keeps it warm
# between phases. ServerAlive keeps a long pg_dump from looking idle.
DB_SSH_CONTROL_DIR="${SYNC_CUTOVER_SSH_CONTROL_DIR:-${STATE_DIR}/ssh}"
db_ssh_opts() {
  mkdir -p "${DB_SSH_CONTROL_DIR}" 2>/dev/null || true
  chmod 0700 "${DB_SSH_CONTROL_DIR}" 2>/dev/null || true
  printf '%s\n' \
    -o BatchMode=yes \
    -o ConnectTimeout=20 \
    -o ConnectionAttempts=5 \
    -o ServerAliveInterval=30 \
    -o ServerAliveCountMax=20 \
    -o ControlMaster=auto \
    -o ControlPersist=900 \
    -o "ControlPath=${DB_SSH_CONTROL_DIR}/cutover-%C"
}

# `lib/db.ts` connects with application_name `omniads-web` / `omniads-worker`.
# Quiescence is decided on ACTUAL backends carrying that name, because that is
# the only thing that says whether application code is touching the database
# right now.
APP_NAME_PREFIX="${SYNC_CUTOVER_APP_NAME_PREFIX:-omniads}"

# The root crontab block this script owns. Everything outside these two markers
# belongs to somebody else — healthz probes, backups, certificate renewals — and
# must survive a cutover byte-for-byte.
ROOTCRON_BEGIN='# BEGIN adsecute-sync'
ROOTCRON_END='# END adsecute-sync'
ROOTCRON_USER="${SYNC_CUTOVER_ROOT_CRONTAB_USER:-root}"

# How the external trigger is actually run. Declared rather than assumed: an
# earlier version accepted a missing systemd unit during quiesce and then
# REQUIRED that same unit to exist when resuming, so a deployment using cron
# would quiesce "successfully" and then fail to resume.
#   systemd:<unit>     systemctl enable/disable --now
#   cron:<file>        a crontab fragment moved aside and back
#   rootcron           a delimited block inside the ROOT crontab
#   compose:<service>  a Compose service stopped and started
#   none               explicitly no external scheduler, and it must be PROVEN
SCHEDULER_SPEC="${SYNC_CUTOVER_SCHEDULER:-}"

EXPECTED_SHA="${DEPLOY_SHA:-}"

# The image repository, as a variable with the post-transfer default.
#
# EXPORTED because this script drives `docker compose up` itself: compose
# resolves `${WEB_IMAGE_REPO:-...}` out of this process's environment, and the
# assertions below are built from the same two variables. That is the point —
# what compose STARTS and what this wrapper CHECKS are one identity, so they
# cannot disagree about which registry a release came from.
#
# Cutting over to a PRE-TRANSFER SHA means setting both to the legacy
# repositories, whose images were never republished under the new owner:
#
#   WEB_IMAGE_REPO=ghcr.io/erhanrdn/omniads-web        # legacy, pre-transfer
#   WORKER_IMAGE_REPO=ghcr.io/erhanrdn/omniads-worker  # legacy, pre-transfer
#
# Export them in the shell that runs this wrapper, so `docker compose up`, the
# image pins and the post-swap readback all resolve the same registry. The full
# procedure is at the top of docker-compose.yml. Nothing here falls back on its
# own — a tag missing from the configured namespace must fail loudly rather than
# quietly resolve somewhere else.
WEB_IMAGE_REPO="${WEB_IMAGE_REPO:-ghcr.io/emrahbilaloglu-ui/omniads-web}"
WORKER_IMAGE_REPO="${WORKER_IMAGE_REPO:-ghcr.io/emrahbilaloglu-ui/omniads-worker}"
export WEB_IMAGE_REPO WORKER_IMAGE_REPO

EXPECTED_WEB_IMAGE="${WEB_IMAGE_REPO}:${EXPECTED_SHA}"
EXPECTED_WORKER_IMAGE="${WORKER_IMAGE_REPO}:${EXPECTED_SHA}"

# Every key this cutover is allowed to change in the env file. `enable` diffs the
# file it produced against the disabled copy and refuses if anything outside this
# set moved, because the rollout script runs inside a container with the whole
# env file mounted and a bug there would otherwise rewrite credentials silently.
MANAGED_ENV_KEY_PATTERN='^ADSECUTE_SYNC_(GLOBAL_ENABLED|LANE_[A-Z0-9_]+_ENABLED)$'

log() { printf '[%s] %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$1"; }
die() { printf '[%s] ABORT %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$1" >&2; exit 1; }

# The ONE place a service name becomes an image reference.
#
# The deploy-disabled swap and the enable recreate each used to spell the
# reference out again inline. Three copies of the same string is exactly how a
# registry change updates two of them and leaves a third comparing against a
# namespace nobody publishes to any more — a check that can now only fail, in the
# middle of a cutover, after the containers have already been swapped.
expected_image_for() {
  case "$1" in
    web) printf '%s' "${EXPECTED_WEB_IMAGE}" ;;
    worker) printf '%s' "${EXPECTED_WORKER_IMAGE}" ;;
    *) die "no expected image is defined for service '$1'" ;;
  esac
}

mkdir -p "${STATE_DIR}"
chmod 0700 "${STATE_DIR}" 2>/dev/null || true
touch "${STATE_FILE}" "${LOCK_FILE}"
chmod 0600 "${STATE_FILE}"

# ── Portable digests ───────────────────────────────────────────────────────
#
# The DB host and the app host are Debian and have `sha256sum`; a developer
# machine driving the harness is macOS and has `shasum`. Picking one and hoping
# is how the integrity check becomes an unconditional die on somebody's laptop.
sha256_file() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | awk '{print $1}'
  else
    shasum -a 256 "$1" | awk '{print $1}'
  fi
}

sha256_stdin() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum | awk '{print $1}'
  else
    shasum -a 256 | awk '{print $1}'
  fi
}

sha256_string() { printf '%s' "$1" | sha256_stdin; }

# Retry a command until it succeeds or the budget runs out.
#
# Everything after `docker compose up -d --force-recreate` was checked ONCE,
# immediately. A recreated container is one second old at that point: Next.js
# has not bound its port and the worker has not written its first heartbeat, so
# the checks measured startup latency rather than health. In production that
# meant /healthz answered "connection reset", enable rolled a correct release
# back, and the staged worker check refused a worker that was still booting.
#
# Bounded, so a genuinely broken release still fails — just not for being young.
wait_for() {
  local what="$1" attempts="$2" delay="$3"
  shift 3
  local attempt=1
  while [ "${attempt}" -le "${attempts}" ]; do
    if "$@"; then
      [ "${attempt}" -eq 1 ] || log "${what}: ready after ${attempt} attempt(s)"
      return 0
    fi
    attempt=$((attempt + 1))
    [ "${attempt}" -le "${attempts}" ] && sleep "${delay}"
  done
  log "${what}: still not ready after ${attempts} attempt(s) over $((attempts * delay))s"
  return 1
}

healthz_answers() { curl -fsS -m 10 http://127.0.0.1:3000/api/healthz >/dev/null 2>&1; }

file_bytes() { wc -c < "$1" | tr -d '[:space:]'; }

# Deliberately NO remote-hashing helper here. Every file this script needs a
# digest of is local to it: the backup artifact is streamed back over SSH and
# lands on this host. A helper that hashed "over there" existed once and was used
# on the artifact, which by then only existed here — it returned empty, and the
# manifest pinned the artifact to nothing without failing. Hash where the file is.

# ── F21.1: the wrapper proves it is the wrapper that was released ──────────

assert_wrapper_integrity() {
  local expected actual source
  source="${BASH_SOURCE[0]}"
  [ -f "${WRAPPER_MANIFEST}" ] \
    || die "no wrapper manifest at ${WRAPPER_MANIFEST}; this script was not delivered by a deploy. Run '.github/scripts/hetzner-remote.sh deliver_cutover_wrapper' for the release being cut over to."
  expected="$(awk -F= '$1 == "wrapper_sha256" { print $2 }' "${WRAPPER_MANIFEST}" | tr -d '[:space:]')"
  [ -n "${expected}" ] \
    || die "${WRAPPER_MANIFEST} records no wrapper_sha256; refusing to run an unpinned cutover wrapper"
  actual="$(sha256_file "${source}")"
  [ "${actual}" = "${expected}" ] \
    || die "this wrapper hashes ${actual}, the delivered manifest pins ${expected}. The file on this host is not the released cutover script — re-deliver it; do NOT edit it in place."
  log "wrapper integrity OK sha256=${actual}"
}

# ── F21.4: the versioned state record ──────────────────────────────────────
#
# Every phase re-derives the bindings below and compares them to what preflight
# recorded. A cutover that drifts — a different DEPLOY_SHA, a retagged image, a
# hand-edited env file, a swapped database, a scheduler rewired underneath it,
# a replaced backup — must stop at the next phase boundary rather than complete
# on top of premises that are no longer true.

state_get() {
  awk -F= -v key="$1" '$1 == key { sub(/^[^=]*=/, ""); print; exit }' "${STATE_FILE}"
}

state_set() {
  local key="$1" value="$2" tmp
  tmp="$(mktemp "${STATE_DIR}/state.XXXXXX")"
  awk -F= -v key="${key}" '$1 != key { print }' "${STATE_FILE}" > "${tmp}"
  printf '%s=%s\n' "${key}" "${value}" >> "${tmp}"
  chmod 0600 "${tmp}"
  mv "${tmp}" "${STATE_FILE}"
}

state_chain() { state_get phase_chain; }

state_chain_has() {
  case ",$(state_chain)," in
    *",$1,"*) return 0 ;;
    *) return 1 ;;
  esac
}

state_chain_add() {
  local chain
  chain="$(state_chain)"
  if state_chain_has "$1"; then return 0; fi
  if [ -z "${chain}" ]; then chain="$1"; else chain="${chain},$1"; fi
  state_set phase_chain "${chain}"
}

state_chain_drop() {
  local chain out=""
  chain="$(state_chain)"
  local IFS=,
  for item in ${chain}; do
    local keep=yes
    for drop in "$@"; do
      [ "${item}" = "${drop}" ] && keep=no
    done
    if [ "${keep}" = "yes" ]; then
      if [ -z "${out}" ]; then out="${item}"; else out="${out},${item}"; fi
    fi
  done
  state_set phase_chain "${out}"
}

require_phase() {
  state_chain_has "$1" \
    || die "phase '$1' has not completed in this cutover (chain='$(state_chain)'); run it first"
  [ "$(state_get invalidated)" != "yes" ] \
    || die "this cutover was INVALIDATED at $(state_get invalidated_utc) after '$(state_get invalidated_after)'. Every runtime proof it held is void; re-run deploy-disabled to re-establish one."
}

require_sha() {
  [ -n "${EXPECTED_SHA}" ] || die "DEPLOY_SHA is required and must be the exact commit being cut over to"
  case "${EXPECTED_SHA}" in
    *[!0-9a-f]* | "") die "DEPLOY_SHA must be a lowercase hex commit sha" ;;
  esac
}

# ── The Sync release identity record ─────────────────────────────────────────
#
# A dedicated, root-owned, atomically written record of WHICH RELEASE this
# cutover is. It exists because `current-build-info.json` is written by an
# unrelated workflow: racing or clobbering that file would corrupt a diagnostic
# somebody else owns, and it never described the deployed image anyway.
#
# What it binds, and why each field is load-bearing:
#   source_sha          the commit being cut over to
#   base_sha            the commit it was built ON, so a rebase is visible
#   remote_branch_sha   what the pushed branch resolves to; a deploy from an
#                       unpushed tree is untraceable
#   *_image_id          immutable image ids — a TAG can be moved, an id cannot
#   *_image_revision    the OCI revision LABEL baked into the image, which is
#                       the only thing that ties an image id back to a commit
#   wrapper/manifest/policy sha256  the exact cutover tooling in force
#   backup_manifest_id  the rollback artifact this cutover is authorised against
#   prev_*              the exact identity a rollback must restore
#
# It carries no secret: shas, ids, digests, paths and a phase name.
RELEASE_RECORD="${SYNC_CUTOVER_RELEASE_RECORD:-${STATE_DIR}/sync-release-identity}"
RELEASE_RECORD_VERSION=1

release_get() {
  [ -f "${RELEASE_RECORD}" ] || return 0
  awk -F= -v key="$1" '$1 == key { sub(/^[^=]*=/, ""); print; exit }' "${RELEASE_RECORD}"
}

# Atomic: write a temp file in the SAME directory, fsync-ish via mv, then mode.
# A partial write must never be readable as a valid record, so the temp file is
# created 0600 before any content reaches it and the rename is the commit point.
release_set() {
  local key="$1" value="$2" tmp
  case "${key}" in
    *[!a-z0-9_]*) die "refusing to write release record key '${key}'" ;;
  esac
  tmp="$(mktemp "${STATE_DIR}/relrec.XXXXXX")"
  chmod 0600 "${tmp}"
  if [ -f "${RELEASE_RECORD}" ]; then
    awk -F= -v key="${key}" '$1 != key { print }' "${RELEASE_RECORD}" > "${tmp}"
  fi
  printf '%s=%s
' "${key}" "${value}" >> "${tmp}"
  chown root:root "${tmp}" 2>/dev/null || true
  mv "${tmp}" "${RELEASE_RECORD}"
  chmod 0600 "${RELEASE_RECORD}" 2>/dev/null || true
  chown root:root "${RELEASE_RECORD}" 2>/dev/null || true
}

image_revision_label() {
  docker image inspect "$1" \
    --format '{{index .Config.Labels "org.opencontainers.image.revision"}}' 2>/dev/null || true
}

# Everything the record should say about the release being cut over to, derived
# fresh. Called at preflight to WRITE it and later to CHECK against it.
release_identity_now() {
  printf 'record_version=%s\n' "${RELEASE_RECORD_VERSION}"
  printf 'source_sha=%s\n' "${EXPECTED_SHA}"
  printf 'base_sha=%s\n' "${RELEASE_BASE_SHA:-unset}"
  printf 'remote_branch_sha=%s\n' "${RELEASE_REMOTE_SHA:-unset}"
  printf 'web_image_id=%s\n' "$(docker image inspect "${EXPECTED_WEB_IMAGE}" --format '{{.Id}}' 2>/dev/null || true)"
  printf 'worker_image_id=%s\n' "$(docker image inspect "${EXPECTED_WORKER_IMAGE}" --format '{{.Id}}' 2>/dev/null || true)"
  printf 'web_image_revision=%s\n' "$(image_revision_label "${EXPECTED_WEB_IMAGE}")"
  printf 'worker_image_revision=%s\n' "$(image_revision_label "${EXPECTED_WORKER_IMAGE}")"
  printf 'wrapper_sha256=%s\n' "$(sha256_file "$0")"
  printf 'manifest_sha256=%s\n' "$([ -f "${WRAPPER_MANIFEST}" ] && sha256_file "${WRAPPER_MANIFEST}" || echo missing)"
  printf 'policy_sha256=%s\n' "$([ -f "${RECOVERY_POLICY_FILE}" ] && sha256_file "${RECOVERY_POLICY_FILE}" || echo missing)"
}

# The record must exist, be well-formed, and describe THIS release.
assert_release_record() {
  local context="$1" want got key
  [ -f "${RELEASE_RECORD}" ] \
    || die "no Sync release identity record at ${RELEASE_RECORD}; run preflight for this release first"
  [ "$(release_get record_version)" = "${RELEASE_RECORD_VERSION}" ] \
    || die "release record is version '$(release_get record_version)', this wrapper writes ${RELEASE_RECORD_VERSION}; they do not describe the same release"
  # A truncated record — a partial write, a full disk — must refuse rather than
  # read as "some fields happen to match".
  for key in record_version source_sha web_image_id worker_image_id \
             web_image_revision worker_image_revision wrapper_sha256 \
             manifest_sha256 policy_sha256; do
    [ -n "$(release_get "${key}")" ] \
      || die "release record is missing '${key}'; it is truncated or was written by a different tool. Refusing to ${context}."
  done

  release_identity_now | while IFS= read -r line; do
    key="${line%%=*}"; want="${line#*=}"
    got="$(release_get "${key}")"
    if [ "${want}" != "${got}" ]; then
      printf 'release identity MISMATCH on %s: record=%s now=%s\n' "${key}" "${got}" "${want}" >&2
      exit 90
    fi
  done || die "the release identity changed since preflight; refusing to ${context}"

  # The image must SAY which commit it is. An image whose revision label does
  # not equal the sha being deployed is not this release, whatever its tag says.
  [ "$(release_get web_image_revision)" = "${EXPECTED_SHA}" ] \
    || die "the web image's OCI revision label is '$(release_get web_image_revision)', not ${EXPECTED_SHA}; refusing to ${context}"
  [ "$(release_get worker_image_revision)" = "${EXPECTED_SHA}" ] \
    || die "the worker image's OCI revision label is '$(release_get worker_image_revision)', not ${EXPECTED_SHA}; refusing to ${context}"

  # A deploy from an unpushed tree cannot be traced back to anything.
  if [ -n "${RELEASE_REMOTE_SHA:-}" ] && [ "${RELEASE_REMOTE_SHA}" != "unset" ]; then
    [ "${RELEASE_REMOTE_SHA}" = "${EXPECTED_SHA}" ] \
      || die "the pushed branch resolves to ${RELEASE_REMOTE_SHA}, not the ${EXPECTED_SHA} being deployed; refusing to ${context}"
  fi
}

# After a container swap: what is RUNNING must be the release, not merely
# something that started successfully.
assert_running_image_identity() {
  local svc cid img rev
  for svc in web worker; do
    cid="$(docker compose ps -q "${svc}" 2>/dev/null | head -1)"
    [ -n "${cid}" ] || die "service '${svc}' is not running after the swap; refusing to enable"
    img="$(docker inspect "${cid}" --format '{{.Image}}' 2>/dev/null || true)"
    rev="$(docker inspect "${cid}" --format '{{index .Config.Labels "org.opencontainers.image.revision"}}' 2>/dev/null || true)"
    case "${svc}" in
      web) [ "${img}" = "$(release_get web_image_id)" ] \
             || die "the running web container is image ${img}, the release record pins $(release_get web_image_id); refusing to enable" ;;
      worker) [ "${img}" = "$(release_get worker_image_id)" ] \
             || die "the running worker container is image ${img}, the release record pins $(release_get worker_image_id); refusing to enable" ;;
    esac
    [ "${rev}" = "${EXPECTED_SHA}" ] \
      || die "the running ${svc} container reports revision '${rev}', not ${EXPECTED_SHA}; refusing to enable"
  done
  log "running containers verified against the release record: web+worker both ${EXPECTED_SHA}"
}

# Retagging between phases must refuse. A tag is mutable; the image id is not.
assert_image_pin() {
  local pinned_web pinned_worker web_digest worker_digest
  [ -s "${IMAGE_PIN_FILE}" ] || die "no image pin recorded; run preflight first"
  read -r pinned_web pinned_worker < "${IMAGE_PIN_FILE}"
  web_digest="$(docker image inspect "${EXPECTED_WEB_IMAGE}" --format '{{.Id}}' 2>/dev/null || true)"
  worker_digest="$(docker image inspect "${EXPECTED_WORKER_IMAGE}" --format '{{.Id}}' 2>/dev/null || true)"
  [ "${web_digest}" = "${pinned_web}" ] \
    || die "the web image tag now resolves to ${web_digest}, not the pinned ${pinned_web}; it was retagged mid-cutover"
  [ "${worker_digest}" = "${pinned_worker}" ] \
    || die "the worker image tag now resolves to ${worker_digest}, not the pinned ${pinned_worker}; it was retagged mid-cutover"
}

# ── Two-host primitives ────────────────────────────────────────────────────

# When this is set, EVERY statement db_sql_on runs is executed inside a
# REPEATABLE READ transaction that imports the named exported snapshot, so it
# reads the database as it stood when that snapshot was taken rather than as it
# stands now. Empty means "read live", which is what every caller outside the
# rollback baseline wants.
#
# It is a global rather than an argument on purpose: the four hash functions the
# rollback baseline is made of are security-critical and are not being edited to
# add a parameter. They are called exactly as they always were; only the
# transaction they land in changes.
SNAPSHOT_IMPORT_ID=""

# Run SQL on the DATABASE host. The statement travels on STDIN rather than
# inside a nested shell quote: a hash query contains newlines, single quotes and
# `$` and there is no defensible way to quote that twice through ssh.
db_sql_on() {
  local database="$1" statement="$2" script quiet=""
  script="${statement}"
  if [ -n "${SNAPSHOT_IMPORT_ID}" ]; then
    snapshot_assert_id_shape "${SNAPSHOT_IMPORT_ID}" \
      || die "refusing to run a statement against snapshot identifier '${SNAPSHOT_IMPORT_ID}': it is not a PostgreSQL exported snapshot name"
    # SET TRANSACTION SNAPSHOT has to be the first thing in the transaction, and
    # the transaction has to be REPEATABLE READ or the imported snapshot is
    # discarded at the next statement. `--quiet` is what keeps the BEGIN/SET/
    # COMMIT command tags out of a digest that is read as bare stdout.
    script="BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ;
SET TRANSACTION SNAPSHOT '${SNAPSHOT_IMPORT_ID}';
${statement}
COMMIT;"
    quiet=1
  fi
  if [ -n "${DB_SSH}" ]; then
    local -a opts; IFS=$'\n' read -r -d '' -a opts < <(db_ssh_opts; printf '\0')
    printf '%s\n' "${script}" | ssh "${opts[@]}" "${DB_SSH}" \
      "runuser -u postgres -- psql --dbname=$(printf %q "${database}") ${quiet:+--quiet} -v ON_ERROR_STOP=1 --tuples-only --no-align --file=-"
  else
    printf '%s\n' "${script}" | runuser -u postgres -- psql --dbname="${database}" \
      ${quiet:+--quiet} -v ON_ERROR_STOP=1 --tuples-only --no-align --file=-
  fi
}

db_sql() { db_sql_on "${DB_NAME}" "$1"; }

# Run a command on the DATABASE host.
db_run() {
  if [ -n "${DB_SSH}" ]; then
    local -a opts; IFS=$'\n' read -r -d '' -a opts < <(db_ssh_opts; printf '\0')
    ssh "${opts[@]}" "${DB_SSH}" "$@"
  else
    "$@"
  fi
}

# Write a file on the DATABASE host from stdin.
# No db_write_file(). Nothing this script produces belongs on the database host:
# the artifact is streamed back here, the manifest describes local paths, and the
# state and release records are local by design. The one caller this helper ever
# had was writing the backup manifest onto the wrong machine.

# Local, for the same reason db_write_file is gone: the manifest lives beside the
# artifact on THIS host. Reading it over the SSH link found a same-named path on
# the database host, or nothing at all.
read_manifest_file() {
  cat "$1"
}

# ── A transaction-bound snapshot for the rollback artifact ─────────────────
#
# WHY THIS EXISTS
#
# `take_verified_backup` dumps the database, scratch-restores that dump about
# a hundred minutes later, and compares four hashes. It used to compare the
# RESTORED copy against the LIVE database AS IT STOOD AT COMPARISON TIME. That
# can only agree if nothing wrote to provider_connections,
# integration_credentials, business_provider_accounts or
# provider_account_assignments for the whole window — which is false on a
# running system, and it aborted a production preflight for exactly that reason:
#
#   [16:13:52Z] backup artifact bytes=25113968381 sha256=98b2ba24...
#   [16:14:30Z] Scratch-restoring that artifact ... and reading it back
#   [17:53:37Z] ABORT the restored backup does not reproduce provider_connections
#
# The dump closed at 16:13:52 and max(provider_connections.updated_at) was
# 16:30:06. `connection_generation_hash_on` folds updated_at into its signature,
# so the two digests could not match. The BACKUP was fine. The BASELINE was
# wrong, and a correct rollback artifact was thrown away in the middle of a
# release.
#
# Hashing right after pg_dump returns does NOT fix this. pg_dump's snapshot
# opens when it STARTS, so a reading taken when it finishes still races every
# write made during the dump — the same bug with a smaller window, which is
# worse, because it fails rarely and unreproducibly.
#
# The fix is the only thing that removes the race instead of shrinking it: ONE
# exported snapshot, consumed by BOTH pg_dump and the baseline hashes. An
# exporter session holds a REPEATABLE READ transaction open and publishes its
# snapshot id; `pg_dump --snapshot=<id>` attaches to that snapshot, and each
# baseline hash is read in a transaction that does `SET TRANSACTION SNAPSHOT`.
# The baselines therefore describe exactly the rows the artifact carries, no
# matter what the live database does during the dump or the restore.
#
# HOLDING A TRANSACTION OPEN ON A 70 GB PRODUCTION DATABASE IS A HAZARD
#
# An abandoned REPEATABLE READ transaction pins the xmin horizon and stops
# vacuum reclaiming anything newer than it — on this database that is a real
# incident, not an untidiness. FOUR independent things end this one:
#
#   1. the explicit `snapshot_release` on the success path, which runs as soon
#      as the artifact is closed and pinned rather than at the end of the phase;
#   2. the EXIT/INT/TERM/HUP trap, which runs it again on every failure path,
#      including `die`, a failed dump, a failed restore and a signal;
#   3. the exporter reads its script from a FIFO THIS PROCESS holds open. If
#      this process dies for any reason at all — kill -9, a lost terminal, the
#      app host rebooting — the write end closes, psql reads EOF and exits, and
#      the transaction ends with it;
#   4. the session sets `idle_in_transaction_session_timeout` BEFORE it opens
#      the transaction, so even a wedged SSH channel that never delivers that
#      EOF is bounded by the server itself.
#
# and `snapshot_open` additionally terminates any exporter left behind by an
# earlier run before it starts a new one.
#
# Releasing early is safe. PostgreSQL only requires the exporting transaction to
# outlive the IMPORT: pg_dump imports the snapshot within seconds of starting
# and then holds its own, so ending the exporter mid-dump cannot change a byte
# of the artifact. Proven in the harness (V4b).
SNAPSHOT_HOLD_SECONDS="${SYNC_CUTOVER_SNAPSHOT_HOLD_SECONDS:-3600}"
SNAPSHOT_OPEN_TIMEOUT="${SYNC_CUTOVER_SNAPSHOT_OPEN_TIMEOUT:-120}"

# Only this wrapper ever uses this application_name prefix, so a backend wearing
# it is either the exporter this process started or one an earlier run leaked.
SNAPSHOT_MARKER_PREFIX='adsecute-cutover-snap-'

SNAPSHOT_ID=""
SNAPSHOT_MARKER=""
SNAPSHOT_PID=""
SNAPSHOT_WORKDIR=""
SNAPSHOT_LOG=""
SNAPSHOT_IN_OPEN=0
SNAPSHOT_OUT_OPEN=0

# The subshell depth that owns the exporter and the scratch database.
#
# bash does not run an EXIT trap when a command-substitution subshell ends, so
# `x="$(snapshot_bound some_hash)"` cannot fire the cleanup below. That is the
# behaviour every bash this script runs on has, and it is also exactly the kind
# of thing that would be catastrophic if some future shell disagreed: a release
# fired from inside a `$( )` would terminate the exporter in the middle of the
# dump it is holding a snapshot for. BASH_SUBSHELL has existed since bash 3.0
# and makes the assumption unnecessary — cleanup only ever acts in the shell
# that opened the thing it is cleaning up.
CUTOVER_OWNER_DEPTH=""

# The scratch database the rollback artifact is restored into, while it exists.
# Recorded so that a signal, a timeout or a die during the restore drops it too;
# an abandoned scratch copy of a 70 GB database is not a tidiness problem.
SCRATCH_DB=""

cutover_owns_resources() {
  [ -n "${CUTOVER_OWNER_DEPTH}" ] || return 1
  [ "${BASH_SUBSHELL:-0}" = "${CUTOVER_OWNER_DEPTH}" ]
}

scratch_db_drop() {
  local name="${SCRATCH_DB}"
  [ -n "${name}" ] || return 0
  cutover_owns_resources || return 0
  SCRATCH_DB=""
  db_run "runuser -u postgres -- dropdb --if-exists $(printf %q "${name}")" >/dev/null 2>&1 || true
}

# An exported snapshot name is `<hex>-<hex>-<n>`. Checked rather than trusted:
# the id is interpolated into a SQL string literal, so anything that could carry
# a quote must never reach the server.
snapshot_assert_id_shape() {
  case "$1" in
    "") return 1 ;;
    *[!0-9A-Fa-f-]*) return 1 ;;
    *-*-*) return 0 ;;
    *) return 1 ;;
  esac
}

# The exporter, as a function so `exec` can replace the background subshell —
# `$!` then names the process that actually holds the session, which is what
# makes killing it mean anything.
snapshot_exporter_session() {
  if [ -n "${DB_SSH}" ]; then
    local -a opts; IFS=$'\n' read -r -d '' -a opts < <(db_ssh_opts; printf '\0')
    exec ssh "${opts[@]}" "${DB_SSH}" \
      "runuser -u postgres -- psql --dbname=$(printf %q "${DB_NAME}") --quiet -v ON_ERROR_STOP=1 --tuples-only --no-align --file=-"
  else
    exec runuser -u postgres -- psql --dbname="${DB_NAME}" \
      --quiet -v ON_ERROR_STOP=1 --tuples-only --no-align --file=-
  fi
}

# Terminate exporter backends by application_name, from a SECOND connection.
# This is the one release path that still works when the SSH channel carrying
# the exporter is wedged rather than closed, and it is the reason a lost
# controller cannot outlive its transaction by more than the idle bound.
snapshot_terminate_backends() {
  local pattern="$1" swept
  swept="$(db_sql "SELECT COALESCE(count(pg_terminate_backend(pid)), 0)::text
                   FROM pg_stat_activity
                   WHERE application_name LIKE '${pattern}'
                     AND pid <> pg_backend_pid();" 2>/dev/null | tr -d '[:space:]')" || swept=""
  printf '%s' "${swept}"
}

# Idempotent, callable from any exit path, and it must never itself abort: it
# runs from the EXIT trap, where a failure would replace the real diagnosis.
snapshot_release() {
  local swept
  cutover_owns_resources || return 0
  # 1. The FIFO. Closing the write end is the graceful stop: psql reads EOF and
  #    exits, ending the transaction.
  if [ "${SNAPSHOT_IN_OPEN}" = "1" ]; then exec 8>&-; SNAPSHOT_IN_OPEN=0; fi
  # 2. The local process holding the session open.
  if [ -n "${SNAPSHOT_PID}" ]; then
    kill "${SNAPSHOT_PID}" 2>/dev/null || true
    kill -KILL "${SNAPSHOT_PID}" 2>/dev/null || true
    wait "${SNAPSHOT_PID}" 2>/dev/null || true
    SNAPSHOT_PID=""
  fi
  if [ "${SNAPSHOT_OUT_OPEN}" = "1" ]; then exec 7>&-; SNAPSHOT_OUT_OPEN=0; fi
  # 3. The BACKEND. Steps 1 and 2 act on this host; only this one acts on the
  #    database, and only this one is proof.
  if [ -n "${SNAPSHOT_MARKER}" ]; then
    swept="$(snapshot_terminate_backends "${SNAPSHOT_MARKER}")"
    case "${swept}" in
      "" | 0) : ;;
      *) log "snapshot exporter session terminated on the database host (${swept})" ;;
    esac
    SNAPSHOT_MARKER=""
  fi
  # 4. The temporary files, on this host. The FIFOs and the exporter transcript
  #    are the only things this feature writes anywhere.
  if [ -n "${SNAPSHOT_WORKDIR}" ]; then rm -rf "${SNAPSHOT_WORKDIR}" 2>/dev/null || true; fi
  SNAPSHOT_WORKDIR=""
  SNAPSHOT_LOG=""
  SNAPSHOT_ID=""
  SNAPSHOT_IMPORT_ID=""
  return 0
}

# EVERY exit path, including the ones that are not exits at all. `die` reaches
# this through EXIT; a failed pg_dump reaches it through `die`; a signal reaches
# it directly; and a kill -9 of this process is handled by the FIFO instead.
snapshot_cleanup_and_exit() {
  local rc="$1"
  trap - EXIT HUP INT TERM
  # Order matters: the scratch database is dropped through the same SSH link the
  # exporter uses, so it goes first, while that link is still known to work.
  scratch_db_drop || true
  snapshot_release || true
  exit "${rc}"
}
trap 'snapshot_cleanup_and_exit "$?"' EXIT
trap 'snapshot_cleanup_and_exit 130' INT
trap 'snapshot_cleanup_and_exit 143' TERM
trap 'snapshot_cleanup_and_exit 129' HUP

snapshot_open() {
  local marker line waited fifo_in fifo_out swept
  [ -z "${SNAPSHOT_ID}" ] || die "internal error: a snapshot exporter is already open"
  CUTOVER_OWNER_DEPTH="${BASH_SUBSHELL:-0}"

  case "${SNAPSHOT_HOLD_SECONDS}" in "" | *[!0-9]*) die "SYNC_CUTOVER_SNAPSHOT_HOLD_SECONDS must be a whole number of seconds" ;; esac
  case "${SNAPSHOT_OPEN_TIMEOUT}" in "" | *[!0-9]*) die "SYNC_CUTOVER_SNAPSHOT_OPEN_TIMEOUT must be a whole number of seconds" ;; esac

  # There is deliberately no `pg_dump --help` probe here. pg_dump only honours
  # --help and --version as argv[1]; behind `runuser -u postgres --` and any
  # site wrapper that prepends connection flags it does not, and a probe that
  # answers "unsupported" because of ARGUMENT ORDER would refuse every cutover
  # on a perfectly capable host. An unsupported --snapshot instead fails the
  # dump itself, in milliseconds, before a byte is written — and
  # take_verified_backup names that failure for what it is.

  # A run killed between opening an exporter and releasing it would leave a
  # REPEATABLE READ transaction pinning the xmin horizon.
  swept="$(snapshot_terminate_backends "${SNAPSHOT_MARKER_PREFIX}%")"
  case "${swept}" in
    "" | 0) : ;;
    *) log "released ${swept} snapshot exporter session(s) abandoned by an earlier run" ;;
  esac

  # The one residue no shell can clean up after itself: a `kill -9` of this
  # process leaves the FIFOs behind, because SIGKILL runs no trap. The exporter
  # transaction is still released — the FIFO write end closes with the process —
  # but the directory stays. Swept here, before a new one is made, so the next
  # run heals it instead of accumulating one per abandoned cutover. Safe because
  # LOCK_FILE means there is never a second cutover holding one of these.
  rm -rf "${TMPDIR:-/tmp}"/cutover-snapshot.* 2>/dev/null || true

  SNAPSHOT_WORKDIR="$(mktemp -d "${TMPDIR:-/tmp}/cutover-snapshot.XXXXXX")" \
    || die "could not create a working directory for the snapshot exporter"
  chmod 0700 "${SNAPSHOT_WORKDIR}" 2>/dev/null || true
  fifo_in="${SNAPSHOT_WORKDIR}/in"
  fifo_out="${SNAPSHOT_WORKDIR}/out"
  SNAPSHOT_LOG="${SNAPSHOT_WORKDIR}/transcript"
  mkfifo "${fifo_in}" "${fifo_out}" || die "could not create the snapshot exporter FIFOs under ${SNAPSHOT_WORKDIR}"
  : > "${SNAPSHOT_LOG}"

  marker="${SNAPSHOT_MARKER_PREFIX}$$"

  # BOTH ends opened read-write BEFORE the exporter starts, so neither open()
  # can block and there is no ordering deadlock. Holding the read end of the
  # output FIFO is also what lets the wait below be a bounded `read -t` rather
  # than a poll loop — `sleep` cannot be trusted to sleep in every sandbox this
  # script is exercised in, and a poll that does not pause is not a timeout.
  exec 8<>"${fifo_in}" || die "could not open the snapshot exporter input FIFO"
  SNAPSHOT_IN_OPEN=1
  exec 7<>"${fifo_out}" || die "could not open the snapshot exporter output FIFO"
  SNAPSHOT_OUT_OPEN=1

  # 8>&- 7>&-: the exporter must NOT inherit the write end of its own input
  # FIFO. If it does, closing fd 8 here never produces the EOF that stops it,
  # and the whole "controller dies, transaction ends" guarantee is gone.
  snapshot_exporter_session < "${fifo_in}" > "${fifo_out}" 2>&1 7>&- 8>&- &
  SNAPSHOT_PID=$!
  SNAPSHOT_MARKER="${marker}"

  {
    printf "SELECT set_config('application_name', '%s', false);\n" "${marker}"
    printf "SET statement_timeout = '%ss';\n" "${SNAPSHOT_OPEN_TIMEOUT}"
    printf "SET idle_in_transaction_session_timeout = '%ss';\n" "${SNAPSHOT_HOLD_SECONDS}"
    printf "BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ;\n"
    printf "SELECT 'SNAPSHOT ' || pg_export_snapshot();\n"
  } >&8

  waited=0
  while [ "${waited}" -lt "${SNAPSHOT_OPEN_TIMEOUT}" ]; do
    if IFS= read -r -t 1 line <&7; then
      printf '%s\n' "${line}" >> "${SNAPSHOT_LOG}"
      case "${line}" in
        "SNAPSHOT "*) SNAPSHOT_ID="$(printf '%s' "${line#SNAPSHOT }" | tr -d '[:space:]')"; break ;;
      esac
      continue
    fi
    kill -0 "${SNAPSHOT_PID}" 2>/dev/null || break
    waited=$(( waited + 1 ))
  done

  if ! snapshot_assert_id_shape "${SNAPSHOT_ID}"; then
    log "snapshot exporter transcript: $(tr '\n' ' ' < "${SNAPSHOT_LOG}" 2>/dev/null || true)"
    snapshot_release
    die "could not export a database snapshot on the database host. A backup whose baseline is read at a different instant than the dump is not a verifiable rollback, and this wrapper will not take one."
  fi

  log "snapshot ${SNAPSHOT_ID} exported and held by ${marker}; the dump and every baseline below read THIS snapshot, and the session self-releases after ${SNAPSHOT_HOLD_SECONDS}s idle even if this host disappears"
}

# Runs a command with every db_sql_on statement bound to the exported snapshot.
# Called inside a command substitution, so the assignment is confined to that
# subshell and there is no global to restore — a read that dies mid-way cannot
# leave later live reads silently snapshot-bound.
snapshot_bound() {
  [ -n "${SNAPSHOT_ID}" ] || die "internal error: a snapshot-bound read was attempted with no snapshot open"
  SNAPSHOT_IMPORT_ID="${SNAPSHOT_ID}"
  "$@"
}

# A baseline that could not be read is not a baseline. Every one of these is
# compared against the restored copy, so an empty or malformed value would make
# the comparison vacuous — the exact failure shape the artifact digest check
# further down already exists to prevent.
snapshot_assert_baseline() {
  local name="$1" value="$2"
  case "${value}" in
    "")
      die "the ${name} baseline could not be read under the exported snapshot; the rollback artifact cannot be verified and nothing may proceed" ;;
    empty | absent)
      return 0 ;;
    *[!0-9a-f]*)
      die "the ${name} baseline read under the exported snapshot is '${value}', which is not a digest; the rollback artifact cannot be verified and nothing may proceed" ;;
    *)
      [ "${#value}" -eq 64 ] \
        || die "the ${name} baseline read under the exported snapshot is ${#value} characters, not 64; the rollback artifact cannot be verified and nothing may proceed" ;;
  esac
}

# ── F21.3: root crontab block management ───────────────────────────────────
#
# The Sync/AI entries live in the ROOT crontab next to a healthz probe and
# unrelated jobs. `crontab -r`, a rewritten file, or "comment out everything
# that mentions adsecute" all silently take those unrelated entries down with
# them, and nobody notices until the thing they scheduled fails to run. This
# manages exactly one delimited block and proves, by digest, that every byte
# outside it is unchanged.

rootcron_read() {
  crontab -l -u "${ROOTCRON_USER}" 2>/dev/null || true
}

rootcron_write() {
  crontab -u "${ROOTCRON_USER}" -
}

# Splits the current crontab into "outside" and "block", and prints the line
# index in the outside stream at which the block started (-1 when absent).
rootcron_split() {
  local current="$1" outside="$2" block="$3"
  : > "${outside}"
  : > "${block}"
  awk -v begin="${ROOTCRON_BEGIN}" -v end="${ROOTCRON_END}" \
      -v outside="${outside}" -v block="${block}" '
    BEGIN { inside = 0; found = 0; outcount = 0; startidx = -1 }
    {
      if (!inside && $0 == begin) { inside = 1; found = 1; startidx = outcount; print > block; next }
      if (inside) { print > block; if ($0 == end) { inside = 0 }; next }
      print > outside; outcount++
    }
    END {
      if (inside) exit 3
      if (!found) startidx = -1
      print startidx
    }
  ' "${current}"
}

rootcron_block_hash() {
  local tmp outside block
  tmp="$(mktemp)"; outside="$(mktemp)"; block="$(mktemp)"
  rootcron_read > "${tmp}"
  if rootcron_split "${tmp}" "${outside}" "${block}" >/dev/null; then
    if [ -s "${block}" ]; then
      sha256_file "${block}"
    elif [ -s "${STATE_DIR}/rootcron.block" ]; then
      sha256_file "${STATE_DIR}/rootcron.block"
    else
      printf 'absent'
    fi
  else
    printf 'unterminated'
  fi
  rm -f "${tmp}" "${outside}" "${block}"
}

rootcron_stop() {
  local tmp outside block start
  tmp="$(mktemp)"; outside="$(mktemp)"; block="$(mktemp)"
  rootcron_read > "${tmp}"
  start="$(rootcron_split "${tmp}" "${outside}" "${block}")" \
    || die "the root crontab has a '${ROOTCRON_BEGIN}' with no '${ROOTCRON_END}'; refusing to guess where the managed block ends"
  if [ "${start}" = "-1" ]; then
    log "root crontab has no managed block; nothing to stop"
    rm -f "${tmp}" "${outside}" "${block}"
    return 0
  fi
  # Everything outside the block is what must survive. It is saved with its
  # digest so `resume-scheduler` can prove nothing else changed meanwhile.
  cp "${block}" "${STATE_DIR}/rootcron.block"
  cp "${outside}" "${STATE_DIR}/rootcron.outside"
  chmod 0600 "${STATE_DIR}/rootcron.block" "${STATE_DIR}/rootcron.outside"
  state_set rootcron_block_index "${start}"
  state_set rootcron_outside_sha256 "$(sha256_file "${outside}")"
  state_set rootcron_block_sha256 "$(sha256_file "${block}")"
  rootcron_write < "${outside}"

  # Read back. `crontab` exiting 0 is not proof the daemon accepted the file.
  local verify_tmp verify_outside verify_block
  verify_tmp="$(mktemp)"; verify_outside="$(mktemp)"; verify_block="$(mktemp)"
  rootcron_read > "${verify_tmp}"
  rootcron_split "${verify_tmp}" "${verify_outside}" "${verify_block}" >/dev/null \
    || die "the root crontab is unparseable after removing the managed block"
  [ ! -s "${verify_block}" ] \
    || die "the managed block is still present in the root crontab after removal"
  [ "$(sha256_file "${verify_outside}")" = "$(state_get rootcron_outside_sha256)" ] \
    || die "removing the managed block changed unrelated root crontab lines; the crontab has been rewritten by something else"
  log "root crontab: managed block removed at line ${start}, $(wc -l < "${verify_outside}" | tr -d '[:space:]') unrelated line(s) preserved byte-for-byte"
  rm -f "${tmp}" "${outside}" "${block}" "${verify_tmp}" "${verify_outside}" "${verify_block}"
}

rootcron_start() {
  local saved_block="${STATE_DIR}/rootcron.block"
  [ -s "${saved_block}" ] \
    || die "no saved root crontab block in ${saved_block}; refusing to invent Sync schedule entries"
  local tmp outside block start rebuilt
  tmp="$(mktemp)"; outside="$(mktemp)"; block="$(mktemp)"; rebuilt="$(mktemp)"
  rootcron_read > "${tmp}"
  rootcron_split "${tmp}" "${outside}" "${block}" >/dev/null \
    || die "the root crontab is unparseable; refusing to rewrite it"
  [ ! -s "${block}" ] || die "the managed block is already present; the scheduler was restarted by something else"
  [ "$(sha256_file "${outside}")" = "$(state_get rootcron_outside_sha256)" ] \
    || die "unrelated root crontab lines changed while the Sync block was out. Someone else edited the crontab during the cutover; reconcile by hand before resuming."

  start="$(state_get rootcron_block_index)"
  case "${start}" in "" | *[!0-9]*) start=0 ;; esac
  awk -v idx="${start}" -v blockfile="${saved_block}" '
    BEGIN { emitted = 0 }
    {
      if (NR - 1 == idx) { while ((getline line < blockfile) > 0) print line; close(blockfile); emitted = 1 }
      print
    }
    END { if (!emitted) { while ((getline line < blockfile) > 0) print line; close(blockfile) } }
  ' "${outside}" > "${rebuilt}"
  rootcron_write < "${rebuilt}"

  local verify_tmp verify_outside verify_block
  verify_tmp="$(mktemp)"; verify_outside="$(mktemp)"; verify_block="$(mktemp)"
  rootcron_read > "${verify_tmp}"
  rootcron_split "${verify_tmp}" "${verify_outside}" "${verify_block}" >/dev/null \
    || die "the root crontab is unparseable after restoring the managed block"
  cmp -s "${verify_block}" "${saved_block}" \
    || die "the restored managed block is not byte-identical to the one that was removed"
  [ "$(sha256_file "${verify_outside}")" = "$(state_get rootcron_outside_sha256)" ] \
    || die "restoring the managed block changed unrelated root crontab lines"
  log "root crontab: managed block restored byte-for-byte, unrelated lines untouched"
  rm -f "${tmp}" "${outside}" "${block}" "${rebuilt}" "${verify_tmp}" "${verify_outside}" "${verify_block}"
}

rootcron_state() {
  local tmp outside block
  tmp="$(mktemp)"; outside="$(mktemp)"; block="$(mktemp)"
  rootcron_read > "${tmp}"
  if ! rootcron_split "${tmp}" "${outside}" "${block}" >/dev/null; then
    printf 'unknown'
  elif grep -Eqv '^[[:space:]]*(#.*)?$' "${block}" 2>/dev/null; then
    printf 'running'
  else
    printf 'stopped'
  fi
  rm -f "${tmp}" "${outside}" "${block}"
}

# ── Scheduler control, for whatever the scheduler actually is ──────────────

# `none` is a claim, not an observation. Accepting it on the operator's word is
# how a cutover quiesces "successfully" while a crontab entry keeps firing sync
# runs into a half-migrated database, so every place a scheduler could live is
# checked before the claim is honoured.
assert_no_scheduler_exists() {
  local found=""
  if rootcron_read | grep -Eqi 'adsecute|omniads'; then
    found="${found} root-crontab"
  fi
  if ls /etc/cron.d 2>/dev/null | grep -qi 'adsecute'; then
    found="${found} /etc/cron.d"
  fi
  if command -v systemctl >/dev/null 2>&1 &&
     systemctl list-unit-files 2>/dev/null | grep -Eq 'adsecute.*\.(timer|service)'; then
    found="${found} systemd"
  fi
  if docker compose ps --services 2>/dev/null | grep -qx scheduler; then
    found="${found} compose"
  fi
  [ -z "${found}" ] \
    || die "SYNC_CUTOVER_SCHEDULER=none claims there is no external scheduler, but one was found in:${found}. Declare it explicitly instead."
  log "scheduler=none verified: no root crontab entry, no /etc/cron.d fragment, no systemd unit and no compose service references this application"
}

resolve_scheduler() {
  if [ -n "${SCHEDULER_SPEC}" ]; then
    printf '%s' "${SCHEDULER_SPEC}"
    return 0
  fi
  # Detect, in order of how this deployment is actually wired.
  if [ "$(rootcron_state)" = "running" ]; then
    printf 'rootcron'
    return 0
  fi
  if command -v systemctl >/dev/null 2>&1 &&
     systemctl list-unit-files 2>/dev/null | grep -q '^adsecute-sync-cron.timer'; then
    printf 'systemd:adsecute-sync-cron.timer'
    return 0
  fi
  if [ -f /etc/cron.d/adsecute-sync ]; then
    printf 'cron:/etc/cron.d/adsecute-sync'
    return 0
  fi
  if docker compose ps --services 2>/dev/null | grep -qx scheduler; then
    printf 'compose:scheduler'
    return 0
  fi
  printf 'unresolved'
}

scheduler_stop() {
  local spec="$1"
  case "${spec}" in
    systemd:*) systemctl disable --now "${spec#systemd:}" ;;
    cron:*) mv "${spec#cron:}" "${spec#cron:}.cutover-disabled" ;;
    rootcron) rootcron_stop ;;
    compose:*) docker compose stop "${spec#compose:}" ;;
    none) log "scheduler=none (verified absent); nothing to stop" ;;
    *) die "cannot stop scheduler: '${spec}' is not a supported spec. Set SYNC_CUTOVER_SCHEDULER explicitly." ;;
  esac
}

scheduler_start() {
  local spec="$1"
  case "${spec}" in
    systemd:*) systemctl enable --now "${spec#systemd:}" ;;
    cron:*) mv "${spec#cron:}.cutover-disabled" "${spec#cron:}" ;;
    rootcron) rootcron_start ;;
    compose:*) docker compose up -d "${spec#compose:}" ;;
    none) log "scheduler=none (verified absent); nothing to start" ;;
    *) die "cannot start scheduler: '${spec}' is not a supported spec" ;;
  esac
}

# Prints "running" or "stopped". Never guesses: an unsupported spec is fatal.
scheduler_state() {
  local spec="$1"
  case "${spec}" in
    systemd:*)
      if systemctl is-active --quiet "${spec#systemd:}" 2>/dev/null; then
        printf 'running'
      else
        printf 'stopped'
      fi
      ;;
    cron:*)
      if [ -f "${spec#cron:}" ]; then printf 'running'; else printf 'stopped'; fi
      ;;
    rootcron) rootcron_state ;;
    compose:*)
      case "$(container_state "${spec#compose:}")" in
        running) printf 'running' ;;
        *) printf 'stopped' ;;
      esac
      ;;
    none) printf 'stopped' ;;
    *) printf 'unknown' ;;
  esac
}

# The scheduler identity recorded in the state record. It is deliberately the
# digest of the MANAGED CONTENT, not of the live location, so it is stable while
# the scheduler is stopped — otherwise every phase between quiesce and resume
# would see a "changed" scheduler and refuse.
scheduler_hash() {
  local spec="$1"
  case "${spec}" in
    rootcron) rootcron_block_hash ;;
    systemd:*)
      local unit="${spec#systemd:}" path
      path="$(systemctl show -p FragmentPath --value "${unit}" 2>/dev/null || true)"
      if [ -n "${path}" ] && [ -f "${path}" ]; then sha256_file "${path}"; else sha256_string "${unit}"; fi
      ;;
    cron:*)
      local file="${spec#cron:}"
      if [ -f "${file}" ]; then sha256_file "${file}"
      elif [ -f "${file}.cutover-disabled" ]; then sha256_file "${file}.cutover-disabled"
      else printf 'absent'; fi
      ;;
    compose:*) sha256_string "${spec}" ;;
    none) printf 'none' ;;
    *) printf 'unknown' ;;
  esac
}

