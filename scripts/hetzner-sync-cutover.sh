# Before ANY phase, including `status`: this file must be the released wrapper.
assert_wrapper_integrity

SCHEDULER="$(resolve_scheduler)"

case "${PHASE}" in
  status)
    printf 'state record: %s\n' "${STATE_FILE}"
    cat "${STATE_FILE}"
    printf 'scheduler=%s state=%s hash=%s\n' "${SCHEDULER}" "$(scheduler_state "${SCHEDULER}")" "$(scheduler_hash "${SCHEDULER}")"
    for service in web worker autoheal; do
