    state_set cutover_epoch "${epoch}"
    state_set deploy_sha "${EXPECTED_SHA}"
    state_set web_image_digest "${web_digest}"
    state_set worker_image_digest "${worker_digest}"
    state_set db_identity "${identity}"
    state_set env_file_sha256 "$(env_file_hash)"
    state_set scheduler_spec "${SCHEDULER}"
    state_set scheduler_sha256 "$(scheduler_hash "${SCHEDULER}")"
