    require_phase verify-contract
    assert_state_invariants
    fingerprint_of "${DB_NAME}" > "${STATE_DIR}/fingerprint-post"
    chmod 0600 "${STATE_DIR}/fingerprint-post"
    [ "$(sha256_file "${STATE_DIR}/fingerprint-pre")" = "$(state_get fingerprint_pre_sha256)" ] \
      || die "the pre-migration fingerprint file changed since it was taken; it cannot be compared against"
    [ "$(sha256_file "${STATE_DIR}/credential-census-pre")" = "$(state_get credential_census_pre_sha256)" ] \
      || die "the pre-migration credential census changed since it was taken; it cannot be compared against"
    credential_census_on "${DB_NAME}" > "${STATE_DIR}/credential-census-post"
    chmod 0600 "${STATE_DIR}/credential-census-post"

    # The migration is expand-only. Identity, schema-identity aside, every count
    # and every identity/generation hash must be byte-identical. `schema_identity`
    # is expected to move — that is what the migration does — so it is compared
    # separately rather than silently ignored.
    #
    # `credential_generation_hash` is compared separately too, for a reason that
    # only shows up against real production data: this release's migration
    # deliberately encrypts legacy PLAINTEXT secrets in place. That rewrite is the
    # point of the release, and it necessarily moves a hash taken over the secret
    # values. Comparing the two hashes can only say "different"; it cannot say
    # whether the difference is the intended conversion or a corrupted token. So
    # the hash difference is not ignored and not accepted — it is EXPLAINED,
    # row by row, against a census taken before the migration ran, and accepted
    # only if every single difference is a plaintext secret becoming ciphertext.
    if ! diff -u \
      <(grep -vE '^(schema_identity|credential_generation_hash)=' "${STATE_DIR}/fingerprint-pre") \
      <(grep -vE '^(schema_identity|credential_generation_hash)=' "${STATE_DIR}/fingerprint-post"); then
      die "the migration changed identity, row counts or an identity/generation hash. Do not enable. Restore from ${BACKUP_MANIFEST:-$(state_get backup_manifest_path)}."
    fi
    pre_cred="$(awk -F= '$1=="credential_generation_hash"{print $2}' "${STATE_DIR}/fingerprint-pre")"
    post_cred="$(awk -F= '$1=="credential_generation_hash"{print $2}' "${STATE_DIR}/fingerprint-post")"
    if [ "${pre_cred}" = "${post_cred}" ]; then
      log "credential_generation_hash unchanged"
    else
      assert_credential_change_is_encryption_only \
        "${STATE_DIR}/credential-census-pre" "${STATE_DIR}/credential-census-post"
    fi
    pre_schema="$(awk -F= '$1=="schema_identity"{print $2}' "${STATE_DIR}/fingerprint-pre")"
    post_schema="$(awk -F= '$1=="schema_identity"{print $2}' "${STATE_DIR}/fingerprint-post")"
    if [ "${pre_schema}" = "${post_schema}" ]; then
      # The migration made no schema change. That is EITHER "you forgot to
      # migrate" — which is what this guard was written to catch and must keep
      # catching — OR a release whose migration was already applied by an
      # earlier, audited cutover of the same schema.
      #
      # The second case is real and unavoidable: once a cutover has migrated
      # production, any later release carries a migration that is correctly a
      # no-op, and refusing it would mean either never releasing again or
      # restoring a 24 GB backup for the sole purpose of giving the migration
      # something to do. Both are worse than the thing the guard protects
      # against.
      #
      # So the second case is allowed ONLY against evidence, never against a
      # flag. The migration still ran for real and still had to exit 0; what
      # changes is what counts as proof afterwards. The operator must name the
      # prior cutover, and that cutover's own attestation must say the schema is
      # byte-identical to the one in front of us now. Nothing is faked, nothing
      # is skipped, and an unset or mismatched pointer refuses.
      assert_continuation_attestation "${post_schema}"
    fi
    if [ "${pre_schema}" = "${post_schema}" ]; then
      log "schema identity unchanged at ${post_schema} — a continuation, authorised above against a prior cutover's attestation"
    elif [ "${pre_cred}" = "${post_cred}" ]; then
      log "schema identity moved ${pre_schema} -> ${post_schema}, everything else identical"
    else
      log "schema identity moved ${pre_schema} -> ${post_schema}; the only data difference is the explained plaintext-to-ciphertext credential conversion"
    fi
    state_set schema_identity_post "${post_schema}"
    # Written here, by the phase that just proved the schema and the credential
    # state, so a later release can be licensed by evidence this run produced
    # rather than by an assertion someone types on the command line.
    write_migration_attestation "$(state_get cutover_epoch)" "${post_schema}" "$(plaintext_secret_count)"
    state_chain_add fingerprint-post
    state_set updated_utc "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    if [ "${pre_schema}" = "${post_schema}" ]; then
      log "fingerprint-post OK — data identical, schema already at the attested identity"
    elif [ "${pre_cred}" = "${post_cred}" ]; then
      log "fingerprint-post OK — data identical, schema advanced"
    else
      log "fingerprint-post OK — schema advanced; the only data change is the credential encryption, explained row by row"
    fi
    ;;

  deploy-disabled)
    require_sha
    state_chain_has fingerprint-post \
      || die "phase 'fingerprint-post' has not completed in this cutover (chain='$(state_chain)'); run it first"
    assert_state_invariants
    log "Confirming every lane is OFF before the new build starts"
    if grep -Eq '^[[:space:]]*(export[[:space:]]+)?ADSECUTE_SYNC_[A-Z0-9_]+_ENABLED[[:space:]]*=[[:space:]]*enabled' "${ENV_FILE}"; then
      die "a sync lane is already enabled in ${ENV_FILE}; the new build must start disabled"
    fi

    # Nothing is swapped until the release record, the source sha, the pushed
    # branch sha, the image ids and their revision labels, and the wrapper /
    # manifest / policy pins all agree.
    assert_release_record "swap the running containers"
    release_set phase "deploy-disabled:swapping"
    release_set updated_utc "$(date -u +%Y-%m-%dT%H:%M:%SZ)"

    log "Starting web and worker on ${EXPECTED_SHA}, lanes off"
    # The compose file on this host has to be the release's.
    #
    # The cutover gate now refuses ahead of "Sync deploy compose", which is
    # correct — nothing should touch the host before the gate — but it means a
    # cutover-required release never gets its compose file delivered by the
    # ordinary path. Without the passthrough below, `SYNC_WORKER_STAGING_IDLE=1`
    # is silently dropped by compose and the worker crash-loops with every lane
    # off, which reads as "the worker did not come up staged" and hides the real
    # cause. Fail closed and say what to do instead.
    grep -q 'SYNC_WORKER_STAGING_IDLE' docker-compose.yml \
      || die "docker-compose.yml on this host does not pass SYNC_WORKER_STAGING_IDLE through to the worker, so the staged deploy cannot work. This release's compose file was never delivered (the cutover gate correctly stops the deploy before it syncs). Copy docker-compose.yml from ${EXPECTED_SHA} to ${APP_DIR}/docker-compose.yml and re-run."

    # SYNC_WORKER_STAGING_IDLE is what makes a disabled worker possible at all.
    # Without it the worker treats a denied lane as fatal and crash-loops, so
    # there is nothing to inspect and the release cannot be verified before it
    # is enabled. It is set HERE and nowhere else, and `enable` clears it.
    APP_IMAGE_TAG="${EXPECTED_SHA}" APP_BUILD_ID="${EXPECTED_SHA}" \
    SYNC_WORKER_STAGING_IDLE=1 \
      docker compose up -d --force-recreate web worker

    for service in web worker; do
      expected="$(expected_image_for "${service}")"
      actual="$(docker inspect "$(docker compose ps -q "${service}")" --format '{{.Config.Image}}')"
      [ "${actual}" = "${expected}" ] || die "${service} is running ${actual}, expected ${expected}"
      log "${service} image=${actual}"
    done

    log "Checking /healthz and /build-info"
    wait_for "/healthz" 30 2 healthz_answers || die "/healthz did not answer within 60s of the recreate"
    build_id="$(curl -fsS http://127.0.0.1:3000/api/build-info | python3 -c 'import json,sys; print(json.load(sys.stdin).get("buildId") or "")')"
    [ "${build_id}" = "${EXPECTED_SHA}" ] || die "build-info reports '${build_id}', expected ${EXPECTED_SHA}"

    # Effective CONTAINER environment, not the file. Key names and a yes/no
    # only — never a value.
    for service in web worker; do
      id="$(docker compose ps -q "${service}")"
      for key in ADSECUTE_SYNC_GLOBAL_ENABLED DATABASE_URL; do
        if docker exec "${id}" sh -c "test -n \"\${${key}:-}\""; then present=yes; else present=no; fi
        log "${service} env ${key} present=${present}"
        if [ "${key}" = "ADSECUTE_SYNC_GLOBAL_ENABLED" ] && [ "${present}" = "yes" ]; then
          die "${service} started with the master switch set; it must start disabled"
        fi
        if [ "${key}" = "DATABASE_URL" ] && [ "${present}" = "no" ]; then
          die "${service} has no DATABASE_URL; the env file was not sourced"
        fi
      done
    done

    log "Proving the worker registered fresh and no old process is still heartbeating"
    worker_started_at="$(docker inspect "$(docker compose ps -q worker)" --format '{{.State.StartedAt}}')"
    # The STAGED contract, which is a negative one: exactly one fresh worker
    # registered as `disabled`, ZERO online workers, and — proved across every
    # table that can grant one — zero runner leases, zero partition claims, zero
    # checkpoint claims and zero job locks.
    #
    # `--min-online-workers 1` was asserted here before and is unsatisfiable with
    # the lanes off: the worker is admitted to nothing, so nothing is online. The
    # old assertion could only ever pass against a worker that was already doing
    # work, which is the opposite of what this phase exists to establish.
    staged_check() {
      docker compose exec -T worker node --import tsx scripts/sync-worker-healthcheck.ts \
        --expect-staged-idle --online-window-minutes 5 \
        --min-heartbeat-after "${worker_started_at}" >/dev/null 2>&1
    }
    wait_for "staged worker" 30 2 staged_check \
      || die "the worker did not come up staged: expected exactly one fresh DISABLED heartbeat, no online workers and no leases or claims held. See the reason code above."

    # Re-establishing the runtime proof is what clears an earlier invalidation,
    # so an emergency stop can be recovered from without hand-editing state.
    # What is RUNNING must be the release. Starting successfully is not the same
    # as running the right image: a stale tag, a cached layer or a compose file
    # pointing elsewhere all start cleanly and all deploy the wrong thing.
    assert_running_image_identity
    release_set phase "deploy-disabled"
    release_set running_web_image_id "$(docker inspect "$(docker compose ps -q web)" --format '{{.Image}}')"
    release_set running_worker_image_id "$(docker inspect "$(docker compose ps -q worker)" --format '{{.Image}}')"
    release_set updated_utc "$(date -u +%Y-%m-%dT%H:%M:%SZ)"

    state_set invalidated no
    state_set last_failure ""
    state_chain_add deploy-disabled
    state_set updated_utc "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    log "deploy-disabled OK"
    ;;

  enable)
    require_sha
    require_phase deploy-disabled
    assert_state_invariants
    # Re-checked here, not merely inherited from deploy-disabled: a container can
    # be recreated, an image retagged or a compose file edited between the two
    # phases, and enabling lanes is the irreversible half.
    assert_release_record "enable the sync lanes"
    assert_running_image_identity

    DISABLED_ENV_BACKUP="${STATE_DIR}/env.disabled.$(state_get cutover_epoch)"
    cp "${ENV_FILE}" "${DISABLED_ENV_BACKUP}"
    chmod 0600 "${DISABLED_ENV_BACKUP}"
    log "disabled env preserved at ${DISABLED_ENV_BACKUP} (this is the rollback target)"

    log "Updating ONLY the managed lane keys in the preserved env file"
    run_in_pinned_image node --import tsx scripts/global-sync-rollout.ts enable \
      || rollback_enable "the rollout script refused"

    # Prove the rollout touched nothing else. It runs in a container with the
    # whole env file bind-mounted, so "it only writes lane keys" is a claim about
    # code that is easier to verify here than to trust.
    # Only lines that are actually KEY=VALUE assignments. A diff hunk also
    # contains comments and blank lines, and reducing `# managed by ...` with
    # the same sed yields the key name `#`, which matches no managed pattern and
    # rolled the whole enable back — for a comment. The rollout is allowed to
    # write comments; it is not allowed to write unmanaged KEYS.
    changed="$(diff "${DISABLED_ENV_BACKUP}" "${ENV_FILE}" 2>/dev/null |
      grep -E '^[<>]' |
      sed -E 's/^[<>][[:space:]]*//' |
      grep -E '^(export[[:space:]]+)?[A-Za-z_][A-Za-z0-9_]*[[:space:]]*=' |
      sed -E 's/^(export[[:space:]]+)?//; s/[[:space:]]*=.*$//' | sort -u || true)"
    for key in ${changed}; do
      printf '%s' "${key}" | grep -Eq "${MANAGED_ENV_KEY_PATTERN}" \
        || rollback_enable "the rollout changed unmanaged env key '${key}'"
    done
    lanes="$(enabled_lane_keys)"
    [ -n "${lanes}" ] || rollback_enable "no lane is enabled in the env file after the rollout ran"
    log "managed keys changed: $(printf '%s' "${changed}" | tr '\n' ' ')"

    # The file changed. The RUNTIME has not: both processes read their
    # environment at container creation. This recreate is the runtime change,
    # and it is sequential — for the length of the recreate one container runs
    # the new configuration and the other the old.
    log "Recreating web and worker from that same configuration"
    APP_IMAGE_TAG="${EXPECTED_SHA}" APP_BUILD_ID="${EXPECTED_SHA}" \
      SYNC_WORKER_STAGING_IDLE= \
      docker compose up -d --force-recreate web worker \
      || rollback_enable "docker compose could not recreate both containers"

    wait_for "/healthz" 30 2 healthz_answers \
      || rollback_enable "/healthz did not answer after recreate"
    build_id="$(curl -fsS http://127.0.0.1:3000/api/build-info | python3 -c 'import json,sys; print(json.load(sys.stdin).get("buildId") or "")' || true)"
    [ "${build_id}" = "${EXPECTED_SHA}" ] \
      || rollback_enable "build-info reports '${build_id}' after recreate, expected ${EXPECTED_SHA}"

    for service in web worker; do
      id="$(docker compose ps -q "${service}" || true)"
      [ -n "${id}" ] || rollback_enable "${service} has no container after the recreate"
      [ "$(docker inspect "${id}" --format '{{.State.Status}}')" = "running" ] \
        || rollback_enable "${service} is not running after the recreate"
      actual="$(docker inspect "${id}" --format '{{.Config.Image}}')"
      [ "${actual}" = "$(expected_image_for "${service}")" ] \
        || rollback_enable "${service} came back on ${actual}, not the pinned build"
      for lane in ${lanes}; do
        docker exec "${id}" sh -c "test \"\${${lane}:-}\" = enabled" \
          || rollback_enable "${service} did not pick up ${lane}; the recreate did not take effect"
      done
      docker exec "${id}" sh -c 'test -z "${ADSECUTE_SYNC_LANE_RETENTION_ENABLED:-}"' \
        || rollback_enable "${service} has retention enabled; retention must stay off"
      # Staging must be GONE, not merely overridden. A worker that came back
      # still carrying it would register `disabled`, take no lease and process
      # nothing — while every lane reads as enabled, which is the most
      # convincing possible way to look released and do nothing.
      docker exec "${id}" sh -c 'test -z "${SYNC_WORKER_STAGING_IDLE:-}"' \
        || rollback_enable "${service} is still in staging idle mode after enable; it would register disabled and process nothing"
      log "${service} carries $(printf '%s' "${lanes}" | tr '\n' ' ')and retention is off"
    done

    worker_started_at="$(docker inspect "$(docker compose ps -q worker)" --format '{{.State.StartedAt}}')"
    # A freshly enabled worker registers per provider scope on its first tick,
    # not at the instant the container starts. Checked once, immediately, this
    # measured how fast the worker boots.
    for scope in meta google_ads shopify; do
      scope_online() {
        docker compose exec -T worker node --import tsx scripts/sync-worker-healthcheck.ts \
          --provider-scope "${scope}" --online-window-minutes 5 --min-online-workers 1 \
          --min-heartbeat-after "${worker_started_at}" >/dev/null 2>&1
      }
      wait_for "${scope} worker registration" 45 2 scope_online \
        || rollback_enable "no fresh ${scope} worker registration within 90s of the recreate"
      log "${scope} worker registered after ${worker_started_at}"
    done

    # An old worker that survived the recreate would keep leasing partitions
    # against the new schema. A backend older than the new container cannot
    # belong to it.
    stale="$(db_sql "
      SELECT COALESCE(string_agg(pid::text || '|' || COALESCE(application_name, ''), ','), '')
      FROM pg_stat_activity
      WHERE datname = current_database()
        AND backend_type = 'client backend'
        AND application_name LIKE '${APP_NAME_PREFIX}%'
        AND backend_start < timestamptz '${worker_started_at}';
    " | tr -d '[:space:]')"
    [ -z "${stale}" ] \
      || rollback_enable "processes older than the recreate are still attached to the database: ${stale}"
    log "no pre-recreate application backend survives"

    docker compose up -d autoheal
    state_set env_file_sha256 "$(env_file_hash)"
    state_set enabled_lanes "$(printf '%s' "${lanes}" | tr '\n' ',')"
    state_chain_add enable
    state_set updated_utc "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    log "enable OK — the external scheduler is still stopped"
    ;;

  resume-scheduler)
    require_sha
    require_phase enable
    assert_state_invariants
    log "Both processes are proven; restarting the scheduler (${SCHEDULER}) last"
    scheduler_start "${SCHEDULER}"
    observed="$(scheduler_state "${SCHEDULER}")"
    [ "${observed}" = "running" ] || die "scheduler is '${observed}' after start"
    state_set scheduler_sha256 "$(scheduler_hash "${SCHEDULER}")"
    state_chain_add resume-scheduler
    state_set updated_utc "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    log "resume-scheduler OK"
    ;;

  emergency-disable)
    # Always available: no DEPLOY_SHA, no database, no completed phase required.
    # Reports success only after LIVE state is confirmed stopped — "the command
    # returned 0" is not the same as "nothing is running".
    log "EMERGENCY: stopping scheduler (${SCHEDULER}), autoheal, web, worker"
    scheduler_stop "${SCHEDULER}" || true
    docker compose stop autoheal || true
    docker compose stop web worker || true
    failed=0
    for service in autoheal web worker; do
      observed="$(container_state "${service}")"
      log "${service}=${observed}"
      case "${observed}" in
        absent | exited | created) ;;
        *) failed=1 ;;
      esac
    done
    scheduler_observed="$(scheduler_state "${SCHEDULER}")"
    log "scheduler=${SCHEDULER} state=${scheduler_observed}"
    [ "${scheduler_observed}" = "stopped" ] || failed=1
    [ "${failed}" = "0" ] || die "emergency disable did NOT fully take effect; intervene by hand"

    # Everything that was proven about the RUNTIME is now false: the containers
    # that carried the proof are stopped. Leaving `enable` in the chain would let
    # `resume-scheduler` restart the external trigger against a runtime nobody
    # has re-verified, which is the worst possible order of operations.
    state_chain_drop deploy-disabled enable resume-scheduler
    state_set invalidated yes
    state_set invalidated_after "emergency-disable"
    state_set invalidated_utc "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    state_set updated_utc "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    log "emergency-disable CONFIRMED stopped; enable/resume proofs INVALIDATED (chain='$(state_chain)')"
    ;;

  *)
    die "unknown phase '${PHASE}'"
    ;;
esac
